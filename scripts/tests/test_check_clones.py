SCRIPT = (
    Path(__file__).resolve().parents[2]
    / "base-library/library/skills/architecture/code-structure/scripts/check_clones.py"
)
FIXTURES = Path(__file__).parent / "fixtures" / "check_clones"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_clones", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


gate = _load()

GO_BODY = (
    "package xlsx\n\nimport \"fmt\"\n\n"
    "func WriteSheet(rows []string, total int) (string, error) {\n"
    "\tout := \"\"\n"
    "\tfor index, row := range rows {\n"
    "\t\tif row == \"\" {\n"
    "\t\t\treturn \"\", fmt.Errorf(\"row %d is empty of %d\", index, total)\n"
    "\t\t}\n"
    "\t\tout += fmt.Sprintf(\"%d:%s;\", index, row)\n"
    "\t}\n"
    "\treturn out, nil\n"
    "}\n"
)


def _report() -> dict:
    return json.loads((FIXTURES / "report.json").read_text(encoding="utf-8"))


def _git(repo: Path, *args: str) -> None:
    subprocess.run(
        [
            "git", "-C", str(repo),
            "-c", "user.name=gate", "-c", "user.email=gate@example.com",
            "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null",
            *args,
        ],
        check=True,
        capture_output=True,
    )


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    _git(tmp_path, "init", "-q")
    (tmp_path / "api-service/xlsx").mkdir(parents=True)
    (tmp_path / "reporting-service/xlsx").mkdir(parents=True)
    (tmp_path / "gen").mkdir()
    (tmp_path / "docs").mkdir()
    (tmp_path / "api-service/xlsx/sheet.go").write_text(GO_BODY, encoding="utf-8")
    (tmp_path / "reporting-service/xlsx/sheet.go").write_text(GO_BODY, encoding="utf-8")
    (tmp_path / "gen/emit.go").write_text("// Code generated by tool. DO NOT EDIT.\n" + GO_BODY, encoding="utf-8")
    (tmp_path / "docs/notes.md").write_text("# Notes\n\n```go\n" + GO_BODY + "```\n", encoding="utf-8")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-qm", "base")
    return tmp_path


def _stage_copy(repo: Path) -> None:
    (repo / "api-service/xlsx/extra.go").write_text(
        GO_BODY.replace("WriteSheet", "WriteExtra"), encoding="utf-8"
    )
    _git(repo, "add", "api-service/xlsx/extra.go")


def _side(path: str, start: int, end: int):
    return gate.Side(path, start, end)


def _pair(first, second, lines: int = 10, is_new: bool = True):
    return gate.CopyPair(first, second, lines, is_new)


def test_a_hunk_header_with_a_count_adds_that_many_lines():
    diff = "+++ b/a.go\n@@ -3,0 +4,3 @@\n"

    assert gate.parse_span(diff) == {"a.go": [(4, 6)]}


def test_a_hunk_header_without_a_count_adds_one_line():
    diff = "+++ b/a.go\n@@ -3 +4 @@\n"

    assert gate.parse_span(diff) == {"a.go": [(4, 4)]}


def test_a_pure_deletion_hunk_adds_no_lines():
    diff = "+++ b/a.go\n@@ -3,2 +2,0 @@\n"

    assert gate.parse_span(diff) == {"a.go": []}


def test_several_files_and_hunks_keep_their_own_ranges():
    diff = (
        "diff --git a/a.go b/a.go\n+++ b/a.go\n@@ -1 +1,2 @@\n@@ -9,0 +11 @@\n"
        "diff --git a/b/c.py b/b/c.py\n+++ b/b/c.py\n@@ -0,0 +1,5 @@\n"
    )

    assert gate.parse_span(diff) == {"a.go": [(1, 2), (11, 11)], "b/c.py": [(1, 5)]}


def test_a_new_pair_with_an_added_first_side_is_kept():
    pair = _pair(_side("a.go", 5, 14), _side("b.go", 5, 14))

    assert gate.copy_pairs([pair], {"a.go": [(1, 20)]}) == [pair]


def test_a_new_pair_with_only_the_second_side_added_is_kept_with_that_side_first():
    old, added = _side("a.go", 5, 14), _side("b.go", 5, 14)

    assert gate.copy_pairs([_pair(old, added)], {"b.go": [(5, 14)]}) == [_pair(added, old)]


def test_a_new_pair_the_commit_only_edits_inside_is_dropped():
    pair = _pair(_side("a.go", 13, 58), _side("b.go", 19, 64))

    assert gate.copy_pairs([pair], {"a.go": [(55, 58)]}) == []


def test_a_new_pair_counts_once_the_added_lines_reach_the_minimum():
    pair = _pair(_side("a.go", 13, 58), _side("b.go", 19, 64))

    assert gate.copy_pairs([pair], {"a.go": [(10, 14), (56, 60)]}) == [pair]


def test_an_old_pair_is_dropped_even_when_the_commit_touches_it():
    pair = _pair(_side("a.go", 5, 14), _side("b.go", 5, 14), is_new=False)

    assert gate.copy_pairs([pair], {"a.go": [(1, 20)]}) == []


def test_a_new_pair_outside_the_added_lines_is_dropped():
    """A third copy re-pairs the old two as new; only a pair that overlaps the change is the commit's."""
    pair = _pair(_side("a.go", 5, 14), _side("b.go", 5, 14))

    assert gate.copy_pairs([pair], {"a.go": [(20, 30)], "b.go": []}) == []


def test_the_recorded_report_yields_the_new_copy_and_nothing_else(repo: Path):
    _stage_copy(repo)
    limits = gate.threshold(repo)

    pairs = gate.pairs_from_report(_report(), repo, limits)
    kept = gate.copy_pairs(pairs, {"api-service/xlsx/extra.go": [(1, 17)]})

    assert [(p.first.path, p.second.path) for p in kept] == [
        ("api-service/xlsx/extra.go", "api-service/xlsx/sheet.go")
    ]


def test_the_end_of_both_sides_comes_from_the_line_count(repo: Path):
    """The detector's second-side end disagrees with its line count in some pairs."""
    _stage_copy(repo)
    report = {
        "duplicates": [
            {
                "firstFile": {"name": "api-service/xlsx/extra.go", "start": 5, "end": 99},
                "secondFile": {"name": "api-service/xlsx/sheet.go", "start": 7, "end": 99},
                "lines": 4,
                "isNew": True,
            }
        ]
    }

    (pair,) = gate.pairs_from_report(report, repo, gate.threshold(repo))

    assert (pair.first.end, pair.second.end) == (8, 10)


