def test_a_pair_inside_a_declared_coincidence_is_dropped():
    pair = _pair(_side("api-service/errors/map.go", 1, 9), _side("reporting-service/errors/map.go", 1, 9))
    entry = gate.Coincidence(
        files=("api-service/errors/map.go", "reporting-service/errors/*.go"),
        reasons=("the public wire codes", "the internal report codes"),
    )

    assert gate.copy_pairs([pair], {"api-service/errors/map.go": [(1, 9)]}, [entry]) == []


def test_a_coincidence_does_not_cover_a_pair_with_one_file_outside_it():
    pair = _pair(_side("web-app/map.go", 1, 9), _side("api-service/errors/map.go", 1, 9))
    entry = gate.Coincidence(("api-service/errors/map.go",), ("one", "two"))

    assert gate.copy_pairs([pair], {"web-app/map.go": [(1, 9)]}, [entry]) == [pair]


def test_a_coincidence_with_one_reason_fails_even_when_no_pair_uses_it(repo: Path):
    (repo / gate.CONFIG).write_text(
        '[[check-clones.coincidence]]\nfiles = ["a.go", "b.go"]\nreasons = ["only one", "only one"]\n',
        encoding="utf-8",
    )
    _stage_copy(repo)

    problems, pairs = gate.check_clones(repo, lambda root, limits, base: {"duplicates": []})

    assert pairs == []
    assert len(problems) == 1 and "a.go" in problems[0] and "two reasons" in problems[0]


