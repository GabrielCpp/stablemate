def _tarball(binary: str, payload: bytes) -> bytes:
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        info = tarfile.TarInfo(f"package/bin/{binary}")
        info.size = len(payload)
        archive.addfile(info, io.BytesIO(payload))
    return buffer.getvalue()


def _registry(tmp_path: Path, data: bytes) -> Path:
    registry = tmp_path / "registry"
    package = registry / "jscpd-test" / "-"
    package.mkdir(parents=True)
    (package / f"jscpd-test-{gate.JSCPD_VERSION}.tgz").write_bytes(data)
    return registry


def _platforms(data: bytes, integrity: str | None = None) -> dict:
    digest = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode("ascii")
    return {("test", "x64", ""): gate.Platform("jscpd-test", integrity or digest)}


def test_an_unset_cache_variable_names_the_variable():
    with pytest.raises(gate.DetectorMissing, match="STABLEMATE_CACHE_DIR"):
        gate.detector_path({})


def test_the_detector_is_installed_from_a_verified_tarball(tmp_path: Path):
    data = _tarball("jscpd", b"#!/bin/sh\nexit 0\n")
    registry = _registry(tmp_path, data)
    env = {gate.CACHE_ENV: str(tmp_path / "cache")}

    target = gate.ensure_detector(
        env, _platforms(data), ("test", "x64", ""), registry.as_uri(), fetch=_read_url
    )

    assert target == tmp_path / "cache/tools/jscpd" / gate.JSCPD_VERSION / "jscpd"
    assert target.read_bytes() == b"#!/bin/sh\nexit 0\n"
    assert target.stat().st_mode & 0o111
    assert [p.name for p in target.parent.iterdir()] == ["jscpd"]


def _read_url(url: str) -> bytes:
    return Path(url.removeprefix("file://")).read_bytes()


def test_a_wrong_integrity_installs_nothing(tmp_path: Path):
    data = _tarball("jscpd", b"payload")
    registry = _registry(tmp_path, data)
    env = {gate.CACHE_ENV: str(tmp_path / "cache")}
    platforms = _platforms(data, integrity="sha512-AAAA")

    with pytest.raises(gate.DetectorMissing, match="integrity"):
        gate.ensure_detector(env, platforms, ("test", "x64", ""), registry.as_uri(), fetch=_read_url)

    assert not (tmp_path / "cache").exists()


def test_an_installed_detector_is_not_downloaded_again(tmp_path: Path):
    env = {gate.CACHE_ENV: str(tmp_path)}
    target = gate.detector_path(env, "jscpd")
    target.parent.mkdir(parents=True)
    target.write_bytes(b"present")

    def refuse(url: str) -> bytes:
        raise AssertionError(f"downloaded {url}")

    found = gate.ensure_detector(
        env, {("test", "x64", ""): gate.Platform("jscpd-test", "sha512-x")}, ("test", "x64", ""), fetch=refuse
    )

    assert found == target and target.read_bytes() == b"present"


