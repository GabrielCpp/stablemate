"""Guards: the checks a harness runs on each tool call, from one library record to every home."""
from __future__ import annotations

import json
import os
import shlex
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from farrier._vendor.stablemate_core.schema import HomeConfig, Selection
from farrier.home_entries import (
    GUARD_CONTAINER,
    Entry,
    entry_drift,
    read_entry_file,
    read_ledger,
)
from farrier.layers import find_in_layers, layer_dirs, searched_layers
from farrier.renderer import Rendered
from farrier.sources import load_pack, read_yaml
from farrier.user_library import user_library_tables

GUARD_RECORD = "hook.yml"
GUARD_MARK = "# generated by farrier\n"
GUARD_HOME = ".agents/hooks"
CODEX_GUARDS = ".codex/hooks.json"
CODEX_CONFIG = ".codex/config.toml"
RECORD_KEYS = {"command", "watches", "timeout", "status", "not_on"}
KINDS = {"shell", "edit", "read", "search"}
NOT_INSTALLED = {"tests", "__pycache__"}
APPROVE = "Open Codex and run /hooks to approve them. Farrier never approves a guard."
BRIDGE_FILE = ".config/opencode/plugins/farrier-guards.ts"
BRIDGE_MARK = "// generated by farrier\n"
BRIDGE_DEFAULT_SECONDS = 60
BRIDGE = """import { spawn } from "node:child_process"

const GUARDS = @GUARDS@

const SHAPES = {
  bash: (args) => ["Bash", { command: args.command, timeout: args.timeout }],
  read: (args) => ["Read", { file_path: args.filePath }],
  grep: (args) => ["Grep", { pattern: args.pattern, path: args.path }],
  write: (args) => ["Write", { file_path: args.filePath, content: args.content }],
  edit: (args) => [
    "Edit",
    {
      file_path: args.filePath,
      old_string: args.oldString,
      new_string: args.newString,
      replace_all: args.replaceAll,
    },
  ],
  apply_patch: (args) => ["apply_patch", { command: args.patchText }],
}

function verdict(code, stdout, stderr) {
  if (code === 2) return stderr.trim() || "Denied by a guard."
  try {
    const decision = JSON.parse(stdout).hookSpecificOutput
    if (decision?.permissionDecision === "deny") return decision.permissionDecisionReason || "Denied by a guard."
  } catch {}
  return null
}

function ask(guard, call) {
  return new Promise((resolve) => {
    const child = spawn("sh", ["-c", guard.command], { timeout: guard.timeout * 1000 })
    let stdout = ""
    let stderr = ""
    child.stdout.on("data", (chunk) => (stdout += chunk))
    child.stderr.on("data", (chunk) => (stderr += chunk))
    child.on("error", () => resolve(null))
    child.on("close", (code) => resolve(verdict(code, stdout, stderr)))
    child.stdin.on("error", () => {})
    child.stdin.end(call)
  })
}

export const FarrierGuards = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    const shape = SHAPES[input.tool]
    if (!shape) return
    const [tool_name, tool_input] = shape(output.args)
    const call = JSON.stringify({
      hook_event_name: "PreToolUse",
      session_id: input.sessionID,
      cwd: directory,
      tool_name,
      tool_input,
    })
    for (const guard of GUARDS) {
      if (!guard.tools.includes(input.tool)) continue
      const reason = await ask(guard, call)
      if (reason) throw new Error(reason)
    }
  },
})
"""


@dataclass(frozen=True)
class Guard:
    """One guard as the library declares it, in no harness's tool names."""

    name: str
    folder: Path
    command: str
    watches: tuple[str, ...]
    timeout: int | None = None
    status: str | None = None
    not_on: tuple[str, ...] = ()


@dataclass(frozen=True)
class GuardDialect:
    """Where one harness reads its home guards, and its tool name for each kind it has.

    A bridged harness has no command hooks, so its guards reach it through a generated file.
    """

    rel: str
    tools: dict[str, str]
    bridged: bool = False


GUARD_DIALECTS = {
    "claude": GuardDialect(
        ".claude/settings.json",
        {"shell": "Bash", "edit": "Write|Edit|MultiEdit", "read": "Read", "search": "Grep"},
    ),
    "codex": GuardDialect(CODEX_GUARDS, {"shell": "Bash", "edit": "apply_patch"}),
    "opencode": GuardDialect(
        BRIDGE_FILE,
        {"shell": "bash", "edit": "edit|write|apply_patch", "read": "read", "search": "grep"},
        bridged=True,
    ),
}


def guard_catalog() -> list[str]:
    """Every guard folder a library layer provides."""
    return sorted(
        {
            entry.name
            for _layer, directory in layer_dirs("library", "hooks")
            for entry in directory.iterdir()
            if entry.is_dir()
        }
    )


def load_guard(name: str) -> Guard:
    """The guard record ``library/hooks/<name>/hook.yml`` from the highest layer holding it."""
    hit = find_in_layers("library", "hooks", name, GUARD_RECORD)
    if hit is None:
        available = ", ".join(guard_catalog()) or "none"
        raise SystemExit(
            f"error: unknown guard {name!r}. Available: {available}.\n"
            f"Searched these library layers:\n{searched_layers()}"
        )
    _layer, path = hit
    data = read_yaml(path)
    unknown = sorted(set(data) - RECORD_KEYS)
    if unknown:
        raise SystemExit(f"error: {path} has unknown keys: {', '.join(unknown)}.")
    command = data.get("command")
    if not isinstance(command, str) or not command:
        raise SystemExit(f"error: {path} needs a `command`.")
    watches = tuple(str(kind) for kind in data.get("watches") or [])
    strange = sorted(set(watches) - KINDS)
    if strange or not watches:
        raise SystemExit(
            f"error: {path} needs `watches` drawn from {', '.join(sorted(KINDS))}. "
            f"It has: {', '.join(watches) or 'none'}."
        )
    return Guard(
        name,
        path.parent,
        command,
        watches,
        data.get("timeout"),
        data.get("status"),
        tuple(str(harness) for harness in data.get("not_on") or []),
    )


def guard_names(table: Selection) -> set[str]:
    """The guards one harness table selects, directly or through its packs."""
    names = set(table.hooks)
    for pack in table.packs:
        names.update(load_pack(str(pack))["hooks"])
    return names


def selected_guards(home: HomeConfig) -> dict[str, list[Guard]]:
    """Each harness's guards, in a stable order, a harness with none left out."""
    selected: dict[str, list[Guard]] = {}
    for harness, table in user_library_tables(home).items():
        names = guard_names(table)
        if not names:
            continue
        if harness not in GUARD_DIALECTS:
            raise SystemExit(
                f"error: [user_library.{harness}] names guards, and farrier writes them "
                f"only for {', '.join(GUARD_DIALECTS)}."
            )
        selected[harness] = [load_guard(name) for name in sorted(names)]
    return selected


def installed_command(guard: Guard, home: Path) -> str:
    """The record's command, with ``{dir}`` as the folder the guard installs into."""
    return guard.command.replace("{dir}", shlex.quote(str(home / GUARD_HOME / guard.name)))


def watched_tools(guard: Guard, harness: str) -> str:
    """The tools of *harness* that *guard* watches, as a matcher."""
    tools = GUARD_DIALECTS[harness].tools
    seen = [tools[kind] for kind in guard.watches if kind in tools]
    if not seen:
        raise SystemExit(
            f"error: guard {guard.name!r} watches {', '.join(guard.watches)}, which {harness} "
            f"has no tool for. Add `shell` to `watches`, or add {harness} to `not_on`."
        )
    return "|".join(seen)


def guard_group(guard: Guard, harness: str, home: Path) -> dict[str, Any]:
    """The hook group that runs *guard* on *harness*, in the shape both harnesses read."""
    handler: dict[str, Any] = {"type": "command", "command": installed_command(guard, home)}
    if guard.timeout is not None:
        handler["timeout"] = guard.timeout
    if guard.status:
        handler["statusMessage"] = guard.status
    return {"matcher": watched_tools(guard, harness), "hooks": [handler]}


def guard_entries(config: HomeConfig, home: Path) -> list[Entry]:
    """Every guard entry the user_library tables intend, a harness's exception left out."""
    entries: list[Entry] = []
    for harness, guards in selected_guards(config).items():
        if GUARD_DIALECTS[harness].bridged:
            continue
        for guard in guards:
            if harness not in guard.not_on:
                entries.append(
                    Entry(
                        GUARD_DIALECTS[harness].rel,
                        GUARD_CONTAINER,
                        installed_command(guard, home),
                        guard_group(guard, harness, home),
                    )
                )
    return entries


def excepted_guards(config: HomeConfig) -> list[str]:
    """A line per guard a table selects and the guard's record says it cannot serve."""
    return [
        f"Left out on {harness}: guard {guard.name}, whose record says it cannot serve {harness}"
        for harness, guards in selected_guards(config).items()
        for guard in guards
        if harness in guard.not_on
    ]


def bridge_text(guards: list[Guard], harness: str, home: Path) -> str:
    """The plugin that calls each of *guards* before a tool of *harness* runs."""
    table = [
        {
            "name": guard.name,
            "command": installed_command(guard, home),
            "tools": watched_tools(guard, harness).split("|"),
            "timeout": guard.timeout or BRIDGE_DEFAULT_SECONDS,
        }
        for guard in guards
    ]
    return BRIDGE_MARK + BRIDGE.replace("@GUARDS@", json.dumps(table, indent=2, ensure_ascii=False))


def guard_files(config: HomeConfig, home: Path) -> dict[Path, Rendered]:
    """The record and the scripts of every guard some harness installs, and each bridge."""
    outputs: dict[Path, Rendered] = {}
    for harness, guards in selected_guards(config).items():
        served = [guard for guard in guards if harness not in guard.not_on]
        dialect = GUARD_DIALECTS[harness]
        if dialect.bridged and served:
            outputs[home / dialect.rel] = Rendered(bridge_text(served, harness, home), verbatim=True)
        for guard in guards:
            if harness in guard.not_on:
                continue
            target = home / GUARD_HOME / guard.name
            for path in sorted(guard.folder.rglob("*")):
                rel = path.relative_to(guard.folder)
                if path.is_dir() or NOT_INSTALLED.intersection(rel.parts):
                    continue
                text = path.read_text(encoding="utf-8")
                outputs[target / rel] = (
                    Rendered(GUARD_MARK + text, verbatim=True)
                    if rel.as_posix() == GUARD_RECORD
                    else Rendered(text, verbatim=True, executable=os.access(path, os.X_OK))
                )
    return outputs


def approval_keys(path: Path) -> dict[str, str]:
    """Each command in the Codex guard file at *path*, with the key Codex records its approval under."""
    if not path.exists():
        return {}
    groups = json.loads(path.read_text(encoding="utf-8")).get("hooks", {}).get("PreToolUse", [])
    return {
        hook["command"]: f"{path.resolve()}:pre_tool_use:{group}:{handler}"
        for group, entry in enumerate(groups)
        for handler, hook in enumerate(entry.get("hooks", []))
        if "command" in hook
    }


def pending_guards(config: HomeConfig, home: Path) -> list[str]:
    """The installed guards Codex will skip, because no approval is recorded for them."""
    keys = approval_keys(home / CODEX_GUARDS)
    state = read_entry_file(home / CODEX_CONFIG).entries("hooks").get("state", {})
    pending: list[str] = []
    for guard in selected_guards(config).get("codex", []):
        key = keys.get(installed_command(guard, home))
        if key is not None and not state.get(key, {}).get("trusted_hash"):
            pending.append(guard.name)
    return pending


def check_pending(config: HomeConfig, home: Path) -> int:
    """Report the guards still waiting for approval by name, writing nothing."""
    pending = pending_guards(config, home)
    if not pending:
        return 0
    for name in pending:
        print(f"pending approval: Codex skips guard {name}")
    print(APPROVE)
    return 1


def codex_guards_move(home: Path, intended: list[Entry]) -> bool:
    """True when installing *intended* adds, changes or removes a guard Codex holds."""
    drift = entry_drift(home, intended, read_ledger(home))
    return any(item.rel == CODEX_GUARDS for item in drift)
