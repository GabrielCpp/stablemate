def guard_catalog() -> list[str]:
    """Every guard folder a library layer provides."""
    return sorted(
        {
            entry.name
            for _layer, directory in layer_dirs("library", "hooks")
            for entry in directory.iterdir()
            if entry.is_dir()
        }
    )


def load_guard(name: str) -> Guard:
    """The guard record ``library/hooks/<name>/hook.yml`` from the highest layer holding it."""
    hit = find_in_layers("library", "hooks", name, GUARD_RECORD)
    if hit is None:
        available = ", ".join(guard_catalog()) or "none"
        raise SystemExit(
            f"error: unknown guard {name!r}. Available: {available}.\n"
            f"Searched these library layers:\n{searched_layers()}"
        )
    _layer, path = hit
    data = read_yaml(path)
    unknown = sorted(set(data) - RECORD_KEYS)
    if unknown:
        raise SystemExit(f"error: {path} has unknown keys: {', '.join(unknown)}.")
    command = data.get("command")
    if not isinstance(command, str) or not command:
        raise SystemExit(f"error: {path} needs a `command`.")
    when = str(data.get("when") or "tool")
    if when not in MOMENTS:
        raise SystemExit(
            f"error: {path} has `when: {when}`; a guard runs at `tool` (before each watched tool "
            f"call) or at `done` (when the agent ends its turn)."
        )
    watches = tuple(str(kind) for kind in data.get("watches") or [])
    strange = sorted(set(watches) - KINDS)
    if when == "done" and watches:
        raise SystemExit(
            f"error: {path} runs at `done`, when no tool is called, so it has no `watches`."
        )
    if when == "tool" and (strange or not watches):
        raise SystemExit(
            f"error: {path} needs `watches` drawn from {', '.join(sorted(KINDS))}. "
            f"It has: {', '.join(watches) or 'none'}."
        )
    return Guard(
        name,
        path.parent,
        command,
        watches,
        data.get("timeout"),
        data.get("status"),
        tuple(str(harness) for harness in data.get("not_on") or []),
        when,
    )


def guard_names(table: Selection) -> set[str]:
    """The guards one harness table selects, directly or through its packs."""
    names = set(table.hooks)
    for pack in table.packs:
        names.update(load_pack(str(pack))["hooks"])
    return names


def selected_guards(home: HomeConfig) -> dict[str, list[Guard]]:
    """Each harness's guards, in a stable order, a harness with none left out."""
    selected: dict[str, list[Guard]] = {}
    for harness, table in user_library_tables(home).items():
        names = guard_names(table)
        if not names:
            continue
        guards = [load_guard(name) for name in sorted(names)]
        if not GUARD_DIALECTS[harness].at_done:
            unserved = [
                g.name for g in guards if g.when == "done" and harness not in g.not_on
            ]
            if unserved:
                raise SystemExit(
                    f"error: guard {', '.join(unserved)} runs at `done`, and farrier reaches "
                    f"{harness} only before a tool call. Add {harness} to its `not_on`."
                )
        selected[harness] = guards
    return selected


def installed_command(guard: Guard, home: Path, harness: str) -> str:
    """The record's command, with ``{dir}`` as the folder the guard installs into.

    ``{harness}`` becomes the harness that runs it, for a guard whose answer differs by harness.
    """
    folder = shlex.quote(str(home / GUARD_HOME / guard.name))
    return guard.command.replace("{dir}", folder).replace("{harness}", harness)


def watched_tools(guard: Guard, harness: str) -> str:
    """The tools of *harness* that *guard* watches, as a matcher."""
    tools = GUARD_DIALECTS[harness].tools
    seen = [tools[kind] for kind in guard.watches if kind in tools]
    if not seen:
        raise SystemExit(
            f"error: guard {guard.name!r} watches {', '.join(guard.watches)}, which {harness} "
            f"has no tool for. Add `shell` to `watches`, or add {harness} to `not_on`."
        )
    return "|".join(seen)


def guard_group(guard: Guard, harness: str, home: Path) -> dict[str, Any]:
    """The hook group that runs *guard* on *harness*, in the shape both harnesses read."""
    handler: dict[str, Any] = {
        "type": "command",
        "command": installed_command(guard, home, harness),
    }
    if guard.timeout is not None:
        handler["timeout"] = guard.timeout
    if guard.status:
        handler["statusMessage"] = guard.status
    if guard.when == "done":
        return {"hooks": [handler]}
    return {"matcher": watched_tools(guard, harness), "hooks": [handler]}


def guard_entries(config: HomeConfig, home: Path) -> list[Entry]:
    """Every guard entry the user_library tables intend, a harness's exception left out."""
    entries: list[Entry] = []
    for harness, guards in selected_guards(config).items():
        if GUARD_DIALECTS[harness].bridged:
            continue
        for guard in guards:
            if harness not in guard.not_on:
                entries.append(
                    Entry(
                        GUARD_DIALECTS[harness].rel,
                        DONE_CONTAINER if guard.when == "done" else GUARD_CONTAINER,
                        installed_command(guard, home, harness),
                        guard_group(guard, harness, home),
                    )
                )
    return entries


def excepted_guards(config: HomeConfig) -> list[str]:
    """A line per guard a table selects and the guard's record says it cannot serve."""
    return [
        f"Left out on {harness}: guard {guard.name}, whose record says it cannot serve {harness}"
        for harness, guards in selected_guards(config).items()
        for guard in guards
        if harness in guard.not_on
    ]


def bridge_text(guards: list[Guard], harness: str, home: Path) -> str:
    """The plugin or extension that calls each of *guards* before a tool of *harness* runs."""
    table = [
        {
            "name": guard.name,
            "command": installed_command(guard, home, harness),
            "tools": watched_tools(guard, harness).split("|"),
            "timeout": guard.timeout or BRIDGE_DEFAULT_SECONDS,
        }
        for guard in guards
    ]
    template = PI_BRIDGE if harness == "pi" else OPENCODE_BRIDGE
    return BRIDGE_MARK + template.replace(
        "@GUARDS@", json.dumps(table, indent=2, ensure_ascii=False)
    )


def copilot_hook(guard: Guard, harness: str, home: Path) -> dict[str, Any]:
    """The Copilot hook entry that hands one call to *guard* through the bridge."""
    bridge = shlex.quote(str(home / COPILOT_BRIDGE))
    moment = "done" if guard.when == "done" else "tool"
    entry: dict[str, Any] = {
        "type": "command",
        "bash": f"python3 {bridge} {moment} {shlex.quote(installed_command(guard, home, harness))}",
        "timeoutSec": guard.timeout or BRIDGE_DEFAULT_SECONDS,
    }
    if guard.when != "done":
        entry["matcher"] = watched_tools(guard, harness)
    return entry


def copilot_guard_files(
    guards: list[Guard], harness: str, home: Path
) -> dict[Path, Rendered]:
    """Copilot's guard file, whose entries call each guard through the generated bridge."""
    hooks: dict[str, list[dict[str, Any]]] = {}
    for guard in guards:
        event = "agentStop" if guard.when == "done" else "preToolUse"
        hooks.setdefault(event, []).append(copilot_hook(guard, harness, home))
    document = (
        json.dumps({"version": 1, "hooks": hooks}, indent=2, ensure_ascii=False) + "\n"
    )
    return {
        home / COPILOT_GUARDS: Rendered(document, verbatim=True, assumed=True),
        home / COPILOT_BRIDGE: Rendered(COPILOT_BRIDGE_TEXT, verbatim=True),
    }


def antigravity_hook(guard: Guard, harness: str, home: Path) -> dict[str, Any]:
    """The Antigravity hook group that hands one call to *guard* through the bridge."""
    bridge = shlex.quote(str(home / ANTIGRAVITY_BRIDGE))
    moment = "done" if guard.when == "done" else "tool"
    handler: dict[str, Any] = {
        "type": "command",
        "command": f"python3 {bridge} {moment} {shlex.quote(installed_command(guard, home, harness))}",
        "timeout": guard.timeout or BRIDGE_DEFAULT_SECONDS,
    }
    if guard.when == "done":
        return handler
    return {"matcher": watched_tools(guard, harness), "hooks": [handler]}


def antigravity_guard_files(
    guards: list[Guard], harness: str, home: Path
) -> dict[Path, Rendered]:
    """Antigravity's hooks file, whose entries call each guard through the generated bridge."""
    hooks: dict[str, list[dict[str, Any]]] = {}
    for guard in guards:
        event = "Stop" if guard.when == "done" else "PreToolUse"
        hooks.setdefault(event, []).append(antigravity_hook(guard, harness, home))
    document = (
        json.dumps({ANTIGRAVITY_HOOK: hooks}, indent=2, ensure_ascii=False) + "\n"
    )
    return {
        home / ANTIGRAVITY_GUARDS: Rendered(document, verbatim=True, assumed=True),
        home / ANTIGRAVITY_BRIDGE: Rendered(ANTIGRAVITY_BRIDGE_TEXT, verbatim=True),
    }


def guard_files(config: HomeConfig, home: Path) -> dict[Path, Rendered]:
    """The record and the scripts of every guard some harness installs, and each bridge."""
    outputs: dict[Path, Rendered] = {}
    for harness, guards in selected_guards(config).items():
        served = [guard for guard in guards if harness not in guard.not_on]
        dialect = GUARD_DIALECTS[harness]
        if dialect.bridge is not None and served:
            outputs.update(dialect.bridge(served, harness, home))
        for guard in guards:
            if harness in guard.not_on:
                continue
            target = home / GUARD_HOME / guard.name
            for path in sorted(guard.folder.rglob("*")):
                rel = path.relative_to(guard.folder)
                if path.is_dir() or NOT_INSTALLED.intersection(rel.parts):
                    continue
                text = path.read_text(encoding="utf-8")
                outputs[target / rel] = (
                    Rendered(GUARD_MARK + text, verbatim=True)
                    if rel.as_posix() == GUARD_RECORD
                    else Rendered(
                        text, verbatim=True, executable=os.access(path, os.X_OK)
                    )
                )
    return outputs


def approval_keys(path: Path) -> dict[str, str]:
    """Each command in the Codex guard file at *path*, with the key Codex records its approval under."""
    if not path.exists():
        return {}
    hooks = json.loads(path.read_text(encoding="utf-8")).get("hooks", {})
    return {
        hook["command"]: f"{path.resolve()}:{key}:{group}:{handler}"
        for event, key in (("PreToolUse", "pre_tool_use"), ("Stop", "stop"))
        for group, entry in enumerate(hooks.get(event, []))
        for handler, hook in enumerate(entry.get("hooks", []))
        if "command" in hook
    }


def pending_guards(config: HomeConfig, home: Path) -> list[str]:
    """The installed guards Codex will skip, because no approval is recorded for them."""
    keys = approval_keys(home / CODEX_GUARDS)
    state = read_entry_file(home / CODEX_CONFIG).entries("hooks").get("state", {})
    pending: list[str] = []
    for guard in selected_guards(config).get("codex", []):
        key = keys.get(installed_command(guard, home, "codex"))
        if key is not None and not state.get(key, {}).get("trusted_hash"):
            pending.append(guard.name)
    return pending


def check_pending(config: HomeConfig, home: Path) -> int:
    """Report the guards still waiting for approval by name, writing nothing."""
    pending = pending_guards(config, home)
    if not pending:
        return 0
    for name in pending:
        print(f"pending approval: Codex skips guard {name}")
    print(APPROVE)
    return 1


def codex_guards_move(home: Path, intended: list[Entry]) -> bool:
    """True when installing *intended* adds, changes or removes a guard Codex holds."""
    drift = entry_drift(home, intended, read_ledger(home))
    return any(item.rel == CODEX_GUARDS for item in drift)
