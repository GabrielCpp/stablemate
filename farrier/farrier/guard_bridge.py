"""The one script body every bridged harness runs for a guard hook, and the parts that differ per harness."""

from __future__ import annotations

BRIDGE_TEMPLATE = """# generated by farrier
import json
import subprocess
import sys

NAMES = {
@@NAMES@@
}
DENIED = "Denied by a guard."


def first(args, *keys):
    return next((args[key] for key in keys if key in args), None)


@@CLAUDE_INPUT@@


def ask(command, call):
    return subprocess.run(
        ["sh", "-c", command], input=json.dumps(call), capture_output=True, text=True
    )


def answer(stdout):
    try:
        out = json.loads(stdout)
    except ValueError:
        return {}
    if not isinstance(out, dict):
        return {}
    inner = out.get("hookSpecificOutput")
    return inner if isinstance(inner, dict) else out


def tool(command, event):
@@ARGS@@
    name = NAMES.get(event.get("toolName", ""), event.get("toolName", ""))
    done = ask(
        command,
        {
            "hook_event_name": "PreToolUse",
            "session_id": event.get("sessionId"),
            "cwd": event.get("cwd"),
            "tool_name": name,
            "tool_input": claude_input(name, args),
        },
    )
    if done.returncode == 2:
        return @@EXIT_DENY@@
    decision = answer(done.stdout)
@@VERDICT@@
    return None


def stop(command, event):
    done = ask(
        command,
        {
            "hook_event_name": "Stop",
            "session_id": event.get("sessionId"),
            "cwd": event.get("cwd"),
            "transcript_path": event.get("transcriptPath"),
            "stop_hook_active": bool(event.get("@@STOP_KEY@@")),
        },
    )
    if done.returncode == 2:
        return {"decision": "block", "reason": done.stderr.strip() or DENIED}
    decision = answer(done.stdout)
    if decision.get("decision") == "block":
        return {"decision": "block", "reason": decision.get("reason") or DENIED}
    return None


def main():
    moment, command = sys.argv[1], sys.argv[2]
    try:
        event = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        event = {}
    result = (tool if moment == "tool" else stop)(command, event)
    if result is not None:
        print(json.dumps(result))


main()
"""


def render_bridge(
    names: dict[str, str],
    claude_input: str,
    args: str,
    exit_deny: str,
    verdict: str,
    stop_key: str,
) -> str:
    """The bridge script for one harness: its tool names and the sources of the parts that differ."""
    parts = {
        "NAMES": "\n".join(f'    "{key}": "{value}",' for key, value in names.items()),
        "CLAUDE_INPUT": claude_input.strip("\n"),
        "ARGS": args.strip("\n"),
        "EXIT_DENY": exit_deny,
        "VERDICT": verdict.strip("\n"),
        "STOP_KEY": stop_key,
    }
    text = BRIDGE_TEMPLATE
    for key, value in parts.items():
        text = text.replace(f"@@{key}@@", value)
    return text
