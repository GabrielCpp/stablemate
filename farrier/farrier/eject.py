PROVENANCE_KEYS = ("name", "generated_by", "source", "resolve", "do_not_edit")

_ASSET_BANNER = re.compile(
    r"\A<!--\r?\nDO NOT EDIT — generated by farrier from the agent library\.\r?\n"
    r"(?:[^\r\n]*\r?\n)*?Editable path on this machine: `farrier source [^`\r\n]*`\r?\n"
    r"-->\r?\n\r?\n"
)


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def strip_skill_md(text: str) -> str:
    """*text* without the `metadata` keys farrier stamps, every other byte untouched."""
    lines = text.split("\n")
    if lines[0].rstrip("\r") != "---":
        raise SystemExit(
            "SKILL.md has no front matter to strip farrier's metadata from"
        )
    close = next(
        (i for i in range(1, len(lines)) if lines[i].rstrip("\r") == "---"), None
    )
    if close is None:
        raise SystemExit("SKILL.md front matter is never closed")
    start = next(
        (i for i in range(1, close) if lines[i].rstrip("\r") == "metadata:"), None
    )
    if start is None:
        raise SystemExit("SKILL.md carries no `metadata:` block to strip")
    end = start + 1
    while end < close and (not lines[end].strip() or _indent(lines[end]) > 0):
        end += 1
    child_indent = min(
        (_indent(line) for line in lines[start + 1 : end] if line.strip()), default=2
    )
    kept: list[str] = []
    skipping = False
    for line in lines[start + 1 : end]:
        key = re.match(rf" {{{child_indent}}}([\w-]+)[ \t]*:", line)
        if key:
            skipping = key[1] in PROVENANCE_KEYS
        elif line.strip() and _indent(line) <= child_indent:
            skipping = False
        if not skipping:
            kept.append(line)
    if any(line.strip() and not line.lstrip().startswith("#") for line in kept):
        replacement = [lines[start], *kept]
    else:
        replacement = []
    return "\n".join([*lines[:start], *replacement, *lines[end:]])


def strip_asset_banner(text: str) -> str:
    """A bundled markdown file's text without the generated-by banner the renderer prepends."""
    return _ASSET_BANNER.sub("", text, count=1)


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8")


def _write(path: Path, text: str) -> None:
    path.write_bytes(text.encode("utf-8"))


def real_skill_folders(repo: Path, agents: Agents) -> dict[str, list[Path]]:
    """Each farrier-generated skill folder name with its real folders in the non-linked harness dirs."""
    found: dict[str, list[Path]] = {}
    for harness in agents.real_skill_harnesses():
        directory = repo / REPO_SKILL_DIRS[harness]
        if not directory.is_dir():
            continue
        for entry in sorted(directory.iterdir()):
            if (
                entry.is_dir()
                and not entry.is_symlink()
                and is_generated(entry / "SKILL.md")
            ):
                found.setdefault(entry.name, []).append(entry)
    return found


def policy_mappings(config: dict[str, Any], renderer: Renderer, name: str) -> list[int]:
    """The indexes of the localInstructions mappings that list the policy *name*."""
    entries = config.get("localInstructions") or []
    hits: list[int] = []
    for index, mapping in enumerate(entries):
        if any(
            _same_policy(renderer, listed, name)
            for listed in mapping_policy_names(mapping)
        ):
            hits.append(index)
    return hits


def _same_policy(renderer: Renderer, listed: str, name: str) -> bool:
    if listed == name:
        return True
    try:
        return library_name(renderer.policy_source(listed)) == name
    except SystemExit:
        return False


def listed_policies(config: dict[str, Any], renderer: Renderer) -> list[str]:
    """The library names of every policy some localInstructions mapping lists."""
    names: set[str] = set()
    for mapping in config.get("localInstructions") or []:
        for listed in mapping_policy_names(mapping):
            try:
                names.add(library_name(renderer.policy_source(listed)))
            except SystemExit:
                names.add(listed)
    return sorted(names)


def run_eject(repo: Path, name: str) -> int:
    """`farrier eject <name>`: eject the skill or policy it names, or exit listing what can be."""
    config_path = repo / "agents.yml"
    if not config_path.is_file():
        raise SystemExit(f"Missing config: {config_path}")
    text = _read(config_path)
    config = yaml.safe_load(text) or {}
    agents = normalize_agents(config)
    folders = real_skill_folders(repo, agents)
    if name in folders:
        return eject_skill(repo, config_path, text, config, agents, name, folders[name])
    renderer, _roots, _skills = build_renderer(config, repo, agents)
    if policy_mappings(config, renderer, name):
        return eject_policy(repo, config_path, text, config, agents, renderer, name)
    skills = ", ".join(sorted(folders)) or "(none)"
    policies = ", ".join(listed_policies(config, renderer)) or "(none)"
    raise SystemExit(
        f"error: {name!r} is neither a farrier-generated skill folder nor a policy "
        f"listed in localInstructions.\nEjectable skills: {skills}\n"
        f"Ejectable policies: {policies}"
    )


def _selected_ids(config: dict[str, Any], all_skills: list[Source]) -> set[str]:
    include, _prompts, _roots, _scaffolds = collect_selection(config)
    exclude = set((config.get("exclude") or {}).get("skills", []) or [])
    return {source.id for source in selected_sources(all_skills, include, exclude)}


def eject_selection(
    text: str, config: dict[str, Any], source: Source, all_skills: list[Source]
) -> str:
    """*text* edited so that nothing in `agents.yml` selects *source* any more."""
    old = _selected_ids(config, all_skills)
    if source.id not in old:
        return text
    exclude = set((config.get("exclude") or {}).get("skills", []) or [])
    rewrites: dict[str, list[str]] = {}
    for entry in config.get("skills") or []:
        if not isinstance(entry, str) or not matches(source, {entry}):
            continue
        rewrites[entry] = (
            [
                other.id
                for other in all_skills
                if other.id != source.id
                and matches(other, {entry})
                and not matches(other, exclude)
            ]
            if is_glob(entry)
            else []
        )
    edited = rewrite_skills_list(text, rewrites) if rewrites else text
    if source.id in _selected_ids(yaml.safe_load(edited) or {}, all_skills):
        edited = add_excluded_skill(edited, source.id)
    after = _selected_ids(yaml.safe_load(edited) or {}, all_skills)
    if after != old - {source.id}:
        raise SystemExit(
            "error: editing agents.yml would not leave exactly the other skills "
            f"selected (expected {sorted(old - {source.id})}, got {sorted(after)}). "
            "Nothing was written."
        )
    return edited


def eject_skill(
    repo: Path,
    config_path: Path,
    text: str,
    config: dict[str, Any],
    agents: Agents,
    name: str,
    copies: list[Path],
) -> int:
    """Strip farrier's provenance from the skill folder *name* and unselect its library source."""
    if len(copies) > 1:
        listing = ", ".join(path.relative_to(repo).as_posix() for path in copies)
        raise SystemExit(
            f"error: skill {name!r} has real copies in {listing}. Set "
            "`skills_from` on one harness in agents.yml (for example "
            "`codex: {skills_from: claude}`), install again so one copy is left, "
            "then eject."
        )
    folder = copies[0]
    skill_md = folder / "SKILL.md"
    metadata = frontmatter_metadata(_read(skill_md))
    all_skills = load_layered_sources("skill", "library", "skills")
    source = next(
        (
            s
            for s in all_skills
            if library_source_path(s) == metadata.get("source")
            or library_name(s) == metadata.get("name")
        ),
        None,
    )
    if source is None:
        raise SystemExit(
            f"error: no library skill matches {name!r} (source "
            f"{metadata.get('source')!r}), so agents.yml cannot be told to stop "
            "selecting it."
        )

    writes: dict[Path, str] = {}
    for path in sorted(folder.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        original = _read(path)
        if path == skill_md:
            stripped = strip_skill_md(original)
        elif path.suffix == ".md":
            stripped = strip_asset_banner(original)
        else:
            continue
        if is_tagged(stripped):
            raise SystemExit(
                f"error: {path.relative_to(repo).as_posix()} still carries farrier's "
                "mark after stripping it, in a form eject does not recognise. Remove "
                "the mark by hand, then eject again. Nothing was written."
            )
        if stripped != original:
            writes[path] = stripped
    verify_strip(_read(skill_md), writes[skill_md])

    edited = eject_selection(text, config, source, all_skills)
    if edited != text:
        writes[config_path] = edited

    for path, content in writes.items():
        _write(path, content)
    print(
        f"Ejected skill {name!r}: {folder.relative_to(repo).as_posix()} is now "
        f"yours, and agents.yml no longer selects {source.id}."
    )
    return 0


def verify_strip(original: str, stripped: str) -> None:
    """Exit unless *stripped* is *original* minus exactly the stamped metadata keys."""
    before = frontmatter_mapping(original)
    after = frontmatter_mapping(stripped)
    meta = {
        key: value
        for key, value in (before.get("metadata") or {}).items()
        if key not in PROVENANCE_KEYS
    }
    expected = {key: value for key, value in before.items() if key != "metadata"}
    if meta:
        expected["metadata"] = meta
    if after != expected:
        raise SystemExit(
            "error: stripping farrier's metadata changed more than its own keys. "
            "Nothing was written."
        )


def _normalized_text(value: str) -> str:
    return value.rstrip("\n") + "\n"


def eject_policy(
    repo: Path,
    config_path: Path,
    text: str,
    config: dict[str, Any],
    agents: Agents,
    renderer: Renderer,
    name: str,
) -> int:
    """Write the policy *name* into the `text:` of every localInstructions mapping that lists it."""
    target = local_instruction_target(agents)
    entries = config.get("localInstructions") or []
    parsed = local_instructions(config)
    indexes = policy_mappings(config, renderer, name)
    if entry_count(text) != len(entries):
        raise SystemExit(
            "error: eject cannot tell which lines of agents.yml hold each "
            "localInstructions entry. Nothing was written."
        )
    expected = copy.deepcopy(config)
    edited = text
    for index in indexes:
        instruction = parsed[index]
        if not instruction.paths:
            raise SystemExit(
                f"error: localInstructions entry {index + 1} has no paths, so the "
                "policy has no file to render into. Nothing was written."
            )
        listed = [
            n
            for n in mapping_policy_names(entries[index])
            if _same_policy(renderer, n, name)
        ]
        source = renderer.policy_source(listed[0])
        renders = {
            renderer.instruction_part(source, target, repo / rel / "AGENTS.md")
            for rel in instruction.paths
        }
        renderer.check_resolved()
        if len(renders) > 1:
            raise SystemExit(
                f"error: the policy {name!r} renders differently in the paths of "
                f"localInstructions entry {index + 1}: {', '.join(instruction.paths)}. "
                "Split the entry so each path has its own, then eject again. "
                "Nothing was written."
            )
        body = renders.pop()
        existing = mapping_text(entries[index])
        pieces = [piece for piece in (body, existing.strip("\n")) if piece.strip()]
        new_text = _normalized_text("\n\n".join(pieces)) if pieces else None
        if (
            new_text is not None
            and renderer.render_templates(
                new_text, target, repo / instruction.paths[0] / "AGENTS.md"
            ).strip()
            != new_text.strip()
        ):
            raise SystemExit(
                f"error: the policy {name!r} holds text a second template pass would "
                "change, so it cannot live in `text:`. Nothing was written."
            )
        edited = rewrite_local_instruction(
            edited, index, lambda n: _same_policy(renderer, n, name), new_text
        )
        _expect_mapping(expected["localInstructions"][index], renderer, name, new_text)

    after = yaml.safe_load(edited) or {}
    if after != expected:
        raise SystemExit(
            "error: editing agents.yml would change more than the ejected policy's "
            "entries. Nothing was written."
        )
    for index in indexes:
        mapping = after["localInstructions"][index]
        if mapping_text(mapping) != expected["localInstructions"][index].get(
            "text", ""
        ):
            raise SystemExit(
                "error: the written `text:` does not read back. Nothing was written."
            )
        if any(_same_policy(renderer, n, name) for n in mapping_policy_names(mapping)):
            raise SystemExit("error: the policy is still listed. Nothing was written.")
    _write(config_path, edited)
    print(
        f"Ejected policy {name!r} into the text of {len(indexes)} localInstructions "
        "entr" + ("y" if len(indexes) == 1 else "ies") + ". Run `farrier --repo .` "
        "to regenerate the instruction files."
    )
    return 0


def _expect_mapping(
    mapping: dict[str, Any], renderer: Renderer, name: str, new_text: str | None
) -> None:
    """Apply the intended edit to the parsed *mapping*, independently of the line edits."""
    for key in ("policy", "policies"):
        if key not in mapping:
            continue
        value = mapping[key]
        if isinstance(value, list):
            kept = [n for n in value if not _same_policy(renderer, str(n), name)]
            if kept:
                mapping[key] = kept
            else:
                del mapping[key]
        elif _same_policy(renderer, str(value), name):
            del mapping[key]
    if new_text is not None:
        mapping["text"] = new_text
