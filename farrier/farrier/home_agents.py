"""Helper agents: one library record per agent, on the model each harness's profile names."""
from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import tomlkit
import yaml

from farrier._vendor.stablemate_core.profiles import PowerMapping, resolve_delegates
from farrier._vendor.stablemate_core.schema import HomeConfig, Selection
from farrier.frontmatter import frontmatter_mapping, split_front_matter
from farrier.layers import available_names, find_in_layers, searched_layers
from farrier.renderer import Rendered
from farrier.sources import load_pack
from farrier.user_library import user_library_tables

AGENT_MARK = "# generated by farrier\n"
RECORD_KEYS = {"description", "read_only"}
READ_ONLY_TOOLS = ("Read", "Grep", "Glob", "Bash")
WRITE_TOOLS = ("Edit", "Write")
READ_ONLY_PROMPT = "Read only. Never edit, write, commit, or run anything that changes state."
STRONGEST_CODEX_EFFORT = {"xhigh": "high", "max": "high"}
OPENCODE_VARIANT = {"low": "minimal", "medium": "", "high": "high", "xhigh": "max", "max": "max"}


@dataclass(frozen=True)
class HelperAgent:
    """One helper agent as the library declares it, with no model name in it."""

    name: str
    description: str
    prompt: str
    read_only: bool = False


def claude_agent(agent: HelperAgent, role: PowerMapping) -> str:
    tools = READ_ONLY_TOOLS if agent.read_only else READ_ONLY_TOOLS + WRITE_TOOLS
    head: dict[str, object] = {
        "name": agent.name,
        "description": agent.description,
        "model": role.model,
    }
    if role.effort:
        head["effort"] = role.effort
    head["tools"] = ", ".join(tools)
    head["metadata"] = {"generated_by": "farrier"}
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{front}---\n\n{agent.prompt}\n"


def codex_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The Codex agent file, whose prompt states read-only because Codex agents inherit the sandbox."""
    model = str(role.model)
    document = tomlkit.document()
    document["name"] = agent.name
    document["description"] = agent.description
    document["model"] = model.partition("@")[2] or model
    if role.effort:
        document["model_reasoning_effort"] = STRONGEST_CODEX_EFFORT.get(role.effort, role.effort)
    prompt = f"{READ_ONLY_PROMPT}\n\n{agent.prompt}" if agent.read_only else agent.prompt
    document["developer_instructions"] = tomlkit.string(f"{prompt}\n", multiline=True)
    return AGENT_MARK + tomlkit.dumps(document)


def opencode_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The OpenCode agent file, marked in a comment because OpenCode hands unknown keys to the provider."""
    head: dict[str, object] = {
        "description": agent.description,
        "mode": "subagent",
        "model": role.model,
    }
    variant = OPENCODE_VARIANT.get(role.effort, role.effort) if role.effort else ""
    if variant:
        head["variant"] = variant
    if agent.read_only:
        head["permission"] = {"edit": "deny"}
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{AGENT_MARK}{front}---\n\n{agent.prompt}\n"


@dataclass(frozen=True)
class AgentDialect:
    """Where one harness reads its helper agents, and how it spells one."""

    folder: str
    suffix: str
    spell: Callable[[HelperAgent, PowerMapping], str]


AGENT_DIALECTS = {
    "claude": AgentDialect(".claude/agents", ".md", claude_agent),
    "codex": AgentDialect(".codex/agents", ".toml", codex_agent),
    "opencode": AgentDialect(".config/opencode/agents", ".md", opencode_agent),
}


def load_agent(name: str) -> HelperAgent:
    """The agent record ``library/agents/<name>.md`` from the highest layer holding it."""
    hit = find_in_layers("library", "agents", f"{name}.md")
    if hit is None:
        available = ", ".join(available_names("library", "agents", suffix=".md")) or "none"
        raise SystemExit(
            f"error: unknown agent {name!r}. Available: {available}.\n"
            f"Searched these library layers:\n{searched_layers()}"
        )
    _layer, path = hit
    text = path.read_text(encoding="utf-8")
    data = frontmatter_mapping(text)
    unknown = sorted(set(data) - RECORD_KEYS)
    if unknown:
        raise SystemExit(f"error: {path} has unknown keys: {', '.join(unknown)}.")
    description = data.get("description")
    if not isinstance(description, str) or not description:
        raise SystemExit(f"error: {path} needs a `description`.")
    prompt = split_front_matter(text)[1].strip()
    if not prompt:
        raise SystemExit(f"error: {path} needs a prompt below its front matter.")
    return HelperAgent(name, description, prompt, data.get("read_only") is True)


def agent_names(table: Selection) -> set[str]:
    """The agents one harness table selects, directly or through its packs."""
    names = set(table.agents)
    for pack in table.packs:
        names.update(load_pack(str(pack))["agents"])
    return names


def role_model(config: HomeConfig, harness: str, name: str) -> PowerMapping:
    """The model *harness* uses for the role *name*, which a selected agent cannot go without."""
    role = resolve_delegates(harness, config.profiles.get(harness)).get(name)
    if role is None:
        raise SystemExit(
            f"error: [user_library.{harness}] selects agent {name!r}, and "
            f"[profiles.{harness}.delegates.{name}] names no model."
        )
    return role


def agent_files(config: HomeConfig, home: Path) -> dict[Path, Rendered]:
    """Every helper agent file the user_library tables intend."""
    outputs: dict[Path, Rendered] = {}
    for harness, table in user_library_tables(config).items():
        names = agent_names(table)
        if not names:
            continue
        dialect = AGENT_DIALECTS.get(harness)
        if dialect is None:
            raise SystemExit(
                f"error: [user_library.{harness}] names agents, and farrier writes them "
                f"only for {', '.join(AGENT_DIALECTS)}."
            )
        for name in sorted(names):
            text = dialect.spell(load_agent(name), role_model(config, harness, name))
            outputs[home / dialect.folder / f"{name}{dialect.suffix}"] = Rendered(text, verbatim=True)
    return outputs
