"""Helper agents: one library record per agent, on the model each harness's profile names."""
from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import tomlkit
import yaml

from farrier._vendor.stablemate_core.profiles import PowerMapping, resolve_delegates
from farrier._vendor.stablemate_core.schema import HomeConfig, Selection
from farrier.frontmatter import frontmatter_mapping, split_front_matter
from farrier.home_mcp import ToolServer, claude_server, copilot_server, load_tool_server
from farrier.layers import available_names, find_in_layers, searched_layers
from farrier.renderer import Rendered
from farrier.sources import load_pack
from farrier.user_library import user_library_tables

AGENT_MARK = "# generated by farrier\n"
RECORD_KEYS = {"description", "read_only", "delegates", "mcp", "session_mcp", "session_tools"}
READ_ONLY_TOOLS = ("Read", "Grep", "Glob", "Bash")
WRITE_TOOLS = ("Edit", "Write")
READ_ONLY_PROMPT = "Read only. Never edit, write, commit, or run anything that changes state."
STRONGEST_CODEX_EFFORT = {"xhigh": "high", "max": "high"}
COPILOT_READ_ONLY_TOOLS = ("read", "search", "execute")
COPILOT_WRITE_TOOLS = ("edit",)
ANTIGRAVITY_MODELS = ("flash", "pro")
ANTIGRAVITY_READ_ONLY_TOOLS = ("read_file", "run_command", "manage_task")
ANTIGRAVITY_WRITE_TOOLS = ("edit_file", "write_file")
OPENCODE_VARIANT = {"low": "minimal", "medium": "", "high": "high", "xhigh": "max", "max": "max"}


@dataclass(frozen=True)
class HelperAgent:
    """One helper agent as the library declares it, with no model name in it."""

    name: str
    description: str
    prompt: str
    read_only: bool = False
    delegates: tuple[str, ...] = ()
    servers: tuple[ToolServer, ...] = ()
    session_servers: tuple[str, ...] = ()
    session_tools: tuple[str, ...] = ()


def refuse_delegates_and_servers(agent: HelperAgent, harness: str) -> None:
    if agent.delegates:
        raise SystemExit(
            f"error: agent {agent.name!r} names `delegates`, and farrier writes delegating "
            f"agents only for claude, copilot and antigravity, not {harness}."
        )
    if agent.servers:
        raise SystemExit(
            f"error: agent {agent.name!r} names `mcp`, and farrier writes agents with their "
            f"own MCP servers only for claude, copilot and antigravity, not {harness}."
        )


def claude_agent(agent: HelperAgent, role: PowerMapping) -> str:
    tools = READ_ONLY_TOOLS if agent.read_only else READ_ONLY_TOOLS + WRITE_TOOLS
    if agent.delegates:
        tools = (*tools, f"Agent({', '.join(agent.delegates)})")
    tools = (*tools, *(f"mcp__{server.name}__*" for server in agent.servers))
    tools = (*tools, *(f"mcp__{name}__*" for name in agent.session_servers))
    tools = (*tools, *agent.session_tools)
    head: dict[str, object] = {
        "name": agent.name,
        "description": agent.description,
        "model": role.model,
    }
    if role.effort:
        head["effort"] = role.effort
    head["tools"] = ", ".join(tools)
    if agent.servers:
        head["mcpServers"] = [{server.name: claude_server(server)} for server in agent.servers]
    head["metadata"] = {"generated_by": "farrier"}
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{front}---\n\n{agent.prompt}\n"


def codex_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The Codex agent file, whose prompt states read-only because Codex agents inherit the sandbox."""
    refuse_delegates_and_servers(agent, "codex")
    model = str(role.model)
    document = tomlkit.document()
    document["name"] = agent.name
    document["description"] = agent.description
    document["model"] = model.partition("@")[2] or model
    if role.effort:
        document["model_reasoning_effort"] = STRONGEST_CODEX_EFFORT.get(role.effort, role.effort)
    prompt = f"{READ_ONLY_PROMPT}\n\n{agent.prompt}" if agent.read_only else agent.prompt
    document["developer_instructions"] = tomlkit.string(f"{prompt}\n", multiline=True)
    return AGENT_MARK + tomlkit.dumps(document)


def copilot_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The Copilot agent file, marked in a comment because Copilot reads its front matter as agent keys."""
    tools = COPILOT_READ_ONLY_TOOLS if agent.read_only else COPILOT_READ_ONLY_TOOLS + COPILOT_WRITE_TOOLS
    if agent.delegates:
        tools = (*tools, "agent")
    tools = (*tools, *(f"{server.name}/*" for server in agent.servers))
    tools = (*tools, *(f"{name}/*" for name in agent.session_servers))
    head: dict[str, object] = {
        "name": agent.name,
        "description": agent.description,
        "model": role.model,
    }
    if role.effort:
        head["reasoningEffort"] = role.effort
    head["tools"] = list(tools)
    if agent.servers:
        head["mcp-servers"] = {server.name: copilot_server(server) for server in agent.servers}
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{AGENT_MARK}{front}---\n\n{agent.prompt}\n"


def opencode_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The OpenCode agent file, marked in a comment because OpenCode hands unknown keys to the provider."""
    refuse_delegates_and_servers(agent, "opencode")
    head: dict[str, object] = {
        "description": agent.description,
        "mode": "subagent",
        "model": role.model,
    }
    variant = OPENCODE_VARIANT.get(role.effort, role.effort) if role.effort else ""
    if variant:
        head["variant"] = variant
    if agent.read_only:
        head["permission"] = {"edit": "deny"}
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{AGENT_MARK}{front}---\n\n{agent.prompt}\n"


def antigravity_server(server: ToolServer) -> dict[str, object]:
    spelled: dict[str, object] = {"name": server.name, "command": server.command, "args": server.args}
    if server.env:
        spelled["env"] = server.env
    return spelled


def antigravity_agent(agent: HelperAgent, role: PowerMapping) -> str:
    """The Antigravity agent file, whose model is `inherit` unless the profile names flash or pro."""
    tools = ANTIGRAVITY_READ_ONLY_TOOLS if agent.read_only else ANTIGRAVITY_READ_ONLY_TOOLS + ANTIGRAVITY_WRITE_TOOLS
    if agent.delegates:
        tools = (*tools, "invoke_subagent")
    head: dict[str, object] = {
        "name": agent.name,
        "description": agent.description,
        "tools": list(tools),
        "model": role.model if role.model in ANTIGRAVITY_MODELS else "inherit",
        "mainAgent": bool(agent.delegates),
        "subagent": not agent.delegates,
    }
    if agent.servers:
        head["mcpServers"] = [antigravity_server(server) for server in agent.servers]
    if agent.session_servers:
        head["inheritMcp"] = True
    front = yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=10**6)
    return f"---\n{AGENT_MARK}{front}---\n\n{agent.prompt}\n"


@dataclass(frozen=True)
class AgentDialect:
    """Where one harness reads its helper agents, and how it spells one."""

    folder: str
    suffix: str
    spell: Callable[[HelperAgent, PowerMapping], str]


AGENT_DIALECTS = {
    "claude": AgentDialect(".claude/agents", ".md", claude_agent),
    "codex": AgentDialect(".codex/agents", ".toml", codex_agent),
    "copilot": AgentDialect(".copilot/agents", ".agent.md", copilot_agent),
    "opencode": AgentDialect(".config/opencode/agents", ".md", opencode_agent),
    "antigravity": AgentDialect(".gemini/config/agents", ".md", antigravity_agent),
}


def load_agent(name: str) -> HelperAgent:
    """The agent record ``library/agents/<name>.md`` from the highest layer holding it."""
    hit = find_in_layers("library", "agents", f"{name}.md")
    if hit is None:
        available = ", ".join(available_names("library", "agents", suffix=".md")) or "none"
        raise SystemExit(
            f"error: unknown agent {name!r}. Available: {available}.\n"
            f"Searched these library layers:\n{searched_layers()}"
        )
    _layer, path = hit
    text = path.read_text(encoding="utf-8")
    data = frontmatter_mapping(text)
    unknown = sorted(set(data) - RECORD_KEYS)
    if unknown:
        raise SystemExit(f"error: {path} has unknown keys: {', '.join(unknown)}.")
    description = data.get("description")
    if not isinstance(description, str) or not description:
        raise SystemExit(f"error: {path} needs a `description`.")
    prompt = split_front_matter(text)[1].strip()
    if not prompt:
        raise SystemExit(f"error: {path} needs a prompt below its front matter.")
    delegates = data.get("delegates", [])
    if not isinstance(delegates, list) or not all(isinstance(each, str) and each for each in delegates):
        raise SystemExit(f"error: {path} `delegates` must list agent names.")
    servers = data.get("mcp", [])
    if not isinstance(servers, list) or not all(isinstance(each, str) and each for each in servers):
        raise SystemExit(f"error: {path} `mcp` must list MCP server names.")
    session_servers = data.get("session_mcp", [])
    if not isinstance(session_servers, list) or not all(
        isinstance(each, str) and each for each in session_servers
    ):
        raise SystemExit(f"error: {path} `session_mcp` must list MCP server names.")
    session_tools = data.get("session_tools", [])
    if not isinstance(session_tools, list) or not all(
        isinstance(each, str) and each for each in session_tools
    ):
        raise SystemExit(f"error: {path} `session_tools` must list tool names.")
    return HelperAgent(
        name,
        description,
        prompt,
        data.get("read_only") is True,
        tuple(delegates),
        tuple(load_tool_server(server) for server in servers),
        tuple(session_servers),
        tuple(session_tools),
    )


def agent_names(table: Selection) -> set[str]:
    """The agents one harness table selects, directly or through its packs."""
    names = set(table.agents)
    for pack in table.packs:
        names.update(load_pack(str(pack))["agents"])
    return names


def role_model(config: HomeConfig, harness: str, name: str) -> PowerMapping:
    """The model *harness* uses for the role *name*, which a selected agent cannot go without."""
    role = resolve_delegates(harness, config.profiles.get(harness)).get(name)
    if role is None:
        raise SystemExit(
            f"error: [user_library.{harness}] selects agent {name!r}, and "
            f"[profiles.{harness}.delegates.{name}] names no model."
        )
    return role


def agent_files(config: HomeConfig, home: Path) -> dict[Path, Rendered]:
    """Every helper agent file the user_library tables intend."""
    outputs: dict[Path, Rendered] = {}
    for harness, table in user_library_tables(config).items():
        names = agent_names(table)
        if not names:
            continue
        dialect = AGENT_DIALECTS[harness]
        for name in sorted(names):
            text = dialect.spell(load_agent(name), role_model(config, harness, name))
            outputs[home / dialect.folder / f"{name}{dialect.suffix}"] = Rendered(text, verbatim=True)
    return outputs
