"""Generation of the ``.agents/`` launcher scaffolding.

The generated make launcher (agents.mk), plus the path constants naming what the
installer writes there.

Farrier installs **skills and prompts**, not workflows — a workflow is a Python
distribution that ships its own console script. But *launching* one in a container
is per-repo generated state again: N concurrent runs of the same workflow need a
distinct run id, container name and volume set each, and none of that is
expressible as a fixed command a reader could be told to type. So the launcher
carries one run target per **installed** workflow, and the list comes from pipx
discovery rather than a hand-maintained selection (see
``docs/plans/container-concurrent-runs.md`` §8.2).
"""
from __future__ import annotations

from collections.abc import Sequence


# Launcher scaffolding generated for every install. These are always-owned
# generated files (registered for --check and cleanup). The thin root Makefile is
# special-cased: it is only written when no root Makefile already exists, and is
# never removed by cleanup (a user may hand-author it).
LAUNCHER_AGENTS_MK = ".agents/agents.mk"
LAUNCHER_CONTEXT_MANIFEST = ".agents/agents-context.json"
# Per-assistant context manifests (one per enabled agent) so a Codex/Copilot run
# resolves instruction_ref to its own adapters. Selected by AGENT_CLI at run time;
# the generic LAUNCHER_CONTEXT_MANIFEST above stays the primary assistant's copy.
LAUNCHER_CONTEXT_MANIFEST_FMT = ".agents/agents-context.{}.json"
LAUNCHER_ROOT_MAKEFILE = "Makefile"
# The compose override farrier generated per installed workflow while workflows
# were a farrier concern. Nothing writes it any more; the constant survives so
# `remove_targets` still deletes a leftover from an older install.
LAUNCHER_COMPOSE = ".agents/local.compose.yaml"


_HEADER = """# Agent launcher — farrier adapter regeneration (generated).
#
# Generated by farrier (the prompt-library installer). Do not edit by hand;
# re-run `make agent-install` to regenerate. Include it from a root Makefile:
#
#   include .agents/agents.mk
#
# Usage:
#   make agent-install             # regenerate the agent adapters from the library
#   make agent-check               # verify adapters are up to date (no writes)
"""

_NO_WORKFLOWS_NOTE = """#
# No containerized run targets: no workflow distribution is installed here. Install
# one (`uv tool install workhorse-workflows`) and re-run `make agent-install`; a
# target appears per discovered workflow. To run one directly, without a container:
#
#   workhorse-<name> run --dry-run     # static preflight, drives nothing
#   workhorse-<name> run
"""

_CORE = """
AGENTS_DIR     ?= $(shell farrier config show library_dir)
# Public stablemate checkout (holds the farrier installer source). Needed only
# for SRC=1 local-source runs.
STABLEMATE_DIR ?= $(shell farrier config show stablemate_dir)

# farrier regenerates these adapters from the prompt library. Default uses the
# installed farrier binary. SRC=1 runs the local source under $(STABLEMATE_DIR)/farrier.
# The library CONTENT is located via `farrier config set-library`; when a
# vigilant-octo checkout exists at $(AGENTS_DIR) we pass --library explicitly.
ifeq ($(SRC),1)
FARRIER ?= uv run --project $(STABLEMATE_DIR)/farrier farrier
endif
FARRIER ?= farrier
FARRIER_LIB_ARG := $(if $(wildcard $(AGENTS_DIR)/library),--library "$(AGENTS_DIR)",)
"""

# The containerized-run plumbing. Emitted only when at least one workflow was
# discovered, so a repo with none renders exactly the two-target launcher it did
# before run targets returned.
#
# Everything here is per-RUN, not per-repo. The compose PROJECT name carries the
# isolation: docker compose namespaces its named volumes by project, so
# `-p coder-<uuid>` gives that run its own workspace/claude-state/runs volumes
# without compose.yaml having to declare anything per-run. That matters most for
# claude-state, which is HOME — two runs sharing it would rotate one
# .credentials.json and last-writer-win each other's .gitconfig.
_RUN_PLUMBING = """
# ── Containerized runs (one container per run) ────────────────────────────────
#
# Each `make agent-run-<workflow>` launch is independent: its own container, its
# own volume set, its own run id. Several may be in flight at once.
#
#   make agent-run-<workflow>              # start a run, streaming its logs
#   make agent-run-<workflow> DETACH=1     # start it in the background
#   make agent-runs                        # list live runs
#   make agent-logs RUN=<workflow>-<id>    # follow one
#   make agent-stop RUN=<workflow>-<id>    # SIGTERM it (resumable: docker restart)
#   make agent-clean RUN=<workflow>-<id>   # remove it AND its volumes (destructive)
#
# The container runs as nobody's uid with YOUR group, so what a run writes into a
# bind-mounted host path stays writable from the host.
AGENT_UID  ?= 65534
AGENT_GID  ?= $(shell id -g)

# The container harness lives in the stablemate checkout, not in a published
# package — compose.yaml/Dockerfile are build inputs, not distribution files.
AGENT_COMPOSE ?= $(STABLEMATE_DIR)/workhorse/compose.yaml

DETACH ?=
AGENT_UP_FLAGS = $(if $(DETACH),--detach,--abort-on-container-exit)

# One launch. $(1) is the workflow name.
#
# The run id is a UUID minted HERE rather than derived inside the container: every
# container starts in the same cwd with the same params, so workhorse's
# params-digest fallback hands every one of them an identical run id, and a second
# run would resume — or delete — the first. An explicit --run-id always wins over
# the digest, so this is a launcher fix: workhorse's digest stays correct for
# interactive local runs, where re-running the same command *should* resume.
#
# The id is interpolated into the container's config at create time, which buys the
# right restart semantics for free: `docker restart` re-enters with the same id and
# resumes from the checkpoint, while a fresh `make` mints a new id and starts clean.
define agent_launch
	set -eu; \\
	run_id="$$(cat /proc/sys/kernel/random/uuid)"; \\
	project="$(1)-$$run_id"; \\
	echo "[agent] workflow  : $(1)"; \\
	echo "[agent] run id    : $$run_id"; \\
	echo "[agent] container : $$project"; \\
	echo "[agent] follow    : make agent-logs RUN=$$project"; \\
	WORKFLOW="$(1)" \\
	AGENT_RUN_ID="$$run_id" \\
	AGENT_UID="$(AGENT_UID)" AGENT_GID="$(AGENT_GID)" \\
	docker compose -p "$$project" -f "$(AGENT_COMPOSE)" up $(AGENT_UP_FLAGS)
endef

# RUN names a launched run by its compose project (`<workflow>-<run-id>`), which is
# what agent-runs prints and what the launch echoed.
define agent_require_run
	@test -n "$(RUN)" || { \\
		echo "set RUN=<workflow>-<run-id> (see: make agent-runs)" >&2; exit 2; }
endef
"""

_REGEN_TARGETS = """
.DEFAULT_GOAL := help

{phony}

help: ## Show available targets
\t@grep -hE '^[a-zA-Z_-]+:.*?## ' $(MAKEFILE_LIST) | sort | \\
\t\tawk 'BEGIN{{FS=":.*?## "}}{{printf "  \\033[36m%-22s\\033[0m %s\\n", $$1, $$2}}'

agent-install: ## Regenerate the agent adapters/skills from the prompt library
\t$(FARRIER) --repo "$(CURDIR)" $(FARRIER_LIB_ARG)

agent-check: ## Verify generated agent adapters are up to date (no writes)
\t@$(FARRIER) --repo "$(CURDIR)" --check $(FARRIER_LIB_ARG) \\
\t\t&& echo "✓ agent files are up to date" \\
\t\t|| {{ echo "↑ files above would be rewritten by 'make agent-install'"; exit 1; }}
"""

_RUN_TARGETS = """
agent-runs: ## List live containerized runs
\t@docker ps --filter label=com.docker.compose.service=agent \\
\t\t--format 'table {{.Label "com.docker.compose.project"}}\\t{{.Status}}\\t{{.Names}}'

agent-logs: ## Follow one run's logs (RUN=<workflow>-<run-id>)
\t$(call agent_require_run)
\t@docker compose -p "$(RUN)" -f "$(AGENT_COMPOSE)" logs -f

agent-stop: ## Stop one run, leaving its volumes so `docker restart` resumes it
\t$(call agent_require_run)
\t@docker compose -p "$(RUN)" -f "$(AGENT_COMPOSE)" stop

agent-clean: ## Remove one run's container AND its per-run volumes (destructive)
\t$(call agent_require_run)
\t@docker compose -p "$(RUN)" -f "$(AGENT_COMPOSE)" down -v
"""


def render_agents_mk(workflows: Sequence[str] = ()) -> str:
    """The make launcher (.agents/agents.mk), generated for every repo.

    Always carries `agent-install` and `agent-check`, which regenerate and verify
    the adapters farrier renders. A root Makefile can `include` it unconditionally.

    ``workflows`` names the workflows installed on this machine (pipx discovery
    supplies it; the empty default renders the adapter-only launcher). Each gets an
    `agent-run-<name>` target launching **one container per run**, so several runs
    of the same workflow can be in flight at once. The discovered set is the only
    source of truth for what is runnable — a selection list in `agents.yml` would
    be a second one, going stale the moment someone pipx-installs or uninstalls.
    """
    names = sorted(workflows)
    if not names:
        phony = ".PHONY: help agent-install agent-check"
        return f"{_HEADER}{_NO_WORKFLOWS_NOTE}{_CORE}{_REGEN_TARGETS.format(phony=phony)}"

    usage = "".join(
        f"#   make agent-run-{name}{' ' * max(1, 21 - len(name))}"
        f"# run the `{name}` workflow in its own container\n"
        for name in names
    )
    phony = (
        ".PHONY: help agent-install agent-check"
        + "".join(f" agent-run-{name}" for name in names)
        + " agent-runs agent-logs agent-stop agent-clean"
    )
    run_targets = "".join(
        f"\nagent-run-{name}: ## Run the `{name}` workflow in its own container\n"
        f"\t@$(call agent_launch,{name})\n"
        for name in names
    )
    return (
        f"{_HEADER}#\n{usage}{_CORE}{_RUN_PLUMBING}"
        f"{_REGEN_TARGETS.format(phony=phony)}{run_targets}{_RUN_TARGETS}"
    )
