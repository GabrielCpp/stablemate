"""Wire farrier's one git-hook command into whichever hook manager the repo uses."""

from __future__ import annotations

import os
import shlex
import subprocess
from pathlib import Path

from farrier._vendor.stablemate_core.base_cache import cache_root
from farrier._vendor.stablemate_core.schema import HOOK_MANAGERS
from farrier.manifest import ConfigLike, as_manifest
from farrier.skill_hooks import STAGES, SkillHook

HOOK_COMMAND = "make farrier-run-hook"

FENCE_START = "# >>> farrier: hooks (generated) >>>"
FENCE_END = "# <<< farrier: hooks <<<"

HOOK_RUNNER = ".agents/hooks/pre-commit"

MESSAGE_RUNNER = ".agents/hooks/commit-msg"

RUNNERS = {"pre-commit": HOOK_RUNNER, "commit-msg": MESSAGE_RUNNER}

MESSAGE_COMMAND = (
    'root=$(git rev-parse --show-toplevel)\n'
    f'if [ -x "$root/{MESSAGE_RUNNER}" ]; then "$root/{MESSAGE_RUNNER}" "$1"; fi'
)

LEFTHOOK_INCLUDE = ".agents/lefthook.farrier.yml"

MANAGERS = HOOK_MANAGERS

_USER_HOOKS = [
    "# The hooks of the skills in this machine's user library.",
    "if command -v farrier >/dev/null 2>&1; then",
    '  farrier hooks run-user --repo "$root"',
    "fi",
    "",
]

_FENCE_FILES = {
    "pre-commit": (".pre-commit-config.yaml",),
    "lefthook": ("lefthook.yml",),
    "husky": (".husky/pre-commit", ".husky/commit-msg"),
    "githooks": (".githooks/pre-commit", ".githooks/commit-msg"),
}

LEGACY_HOOK_MARKER = "# >>> farrier: staged-files gate (generated) >>>"


def configured_manager(config: ConfigLike, repo: Path) -> str:
    """The manager named in `agents.yml`, or the one this repo looks like."""
    declared = as_manifest(config).hooks.manager
    return declared if declared else detect_manager(repo)


def detect_manager(repo: Path) -> str:
    """What the repo looks like, by marker file."""
    for name in (".pre-commit-config.yaml", ".pre-commit-config.yml"):
        if (repo / name).is_file():
            return "pre-commit"
    for name in ("lefthook.yml", "lefthook.yaml", ".lefthook.yml", ".lefthook.yaml"):
        if (repo / name).is_file():
            return "lefthook"
    if (repo / ".husky").is_dir():
        return "husky"
    package = repo / "package.json"
    if package.is_file() and "husky" in package.read_text(encoding="utf-8"):
        return "husky"
    return "githooks"




def fence(body: str) -> str:
    """*body* wrapped in the marker pair, as a block of whole lines."""
    return f"{FENCE_START}\n{body.strip(chr(10))}\n{FENCE_END}\n"


def splice(existing: str, block: str) -> str:
    """*existing* with the farrier fence replaced in place, or appended if absent."""
    lines = existing.splitlines()
    if FENCE_START in lines and FENCE_END in lines:
        head = lines[: lines.index(FENCE_START)]
        tail = lines[lines.index(FENCE_END) + 1 :]
        joined = "\n".join([*head, *block.rstrip("\n").splitlines(), *tail])
        return joined.rstrip("\n") + "\n"
    prefix = existing
    if prefix and not prefix.endswith("\n"):
        prefix += "\n"
    return prefix + block


def unsplice(existing: str) -> str:
    """*existing* with the farrier fence removed."""
    lines = existing.splitlines()
    if FENCE_START not in lines or FENCE_END not in lines:
        return existing
    head = lines[: lines.index(FENCE_START)]
    tail = lines[lines.index(FENCE_END) + 1 :]
    body = "\n".join([*head, *tail]).rstrip("\n")
    return body + "\n" if body else ""


def fenced_body(existing: str) -> str | None:
    """What is currently inside the fence, or None when there is no fence."""
    lines = existing.splitlines()
    if FENCE_START not in lines or FENCE_END not in lines:
        return None
    start = lines.index(FENCE_START)
    end = lines.index(FENCE_END)
    return "\n".join(lines[start + 1 : end])



_PRE_COMMIT_ENTRY = f"""  - repo: local
    hooks:
      - id: farrier-hooks
        name: farrier generated-file gate and skill hooks
        entry: {HOOK_COMMAND}
        language: system
        pass_filenames: false
        stages: [pre-commit]
      - id: farrier-commit-msg
        name: farrier commit-message hooks
        entry: {MESSAGE_RUNNER}
        language: system
        stages: [commit-msg]"""

_LEFTHOOK_ENTRY = f"""extends:
  - {LEFTHOOK_INCLUDE}"""

_LEFTHOOK_FILE = f"""# Generated by farrier. Do not edit — `farrier install` rewrites it.
#
# lefthook.yml carries a one-line `extends:` inside farrier's fence and this file
# carries the commands, so the region spliced into your config stays a reference
# rather than a body that churns whenever a skill selection changes.
pre-commit:
  commands:
    farrier-hooks:
      run: {HOOK_COMMAND}
commit-msg:
  commands:
    farrier-commit-msg:
      run: {MESSAGE_RUNNER} {{1}}
"""

_SHELL_ENTRY = HOOK_COMMAND

def _shell_preamble(rel: str) -> str:
    return (
        "#!/bin/sh\n"
        f"# The repo's {Path(rel).name} hook. Farrier owns only the fenced region below; anything\n"
        "# outside it is yours and survives `farrier install`.\n"
        "set -eu\n"
    )


def body_for(manager: str, rel: str = "") -> str:
    if manager == "pre-commit":
        return _PRE_COMMIT_ENTRY
    if manager == "lefthook":
        return _LEFTHOOK_ENTRY
    if Path(rel).name == "commit-msg":
        return MESSAGE_COMMAND
    return _SHELL_ENTRY


def lefthook_include_text() -> str:
    return _LEFTHOOK_FILE


def runner_text(hooks: list[SkillHook], stage: str = "pre-commit") -> str:
    """`.agents/hooks/<stage>`: every hook declared for *stage*, in selection order."""
    hooks = [hook for hook in hooks if hook.stage == stage]
    user_hooks = _USER_HOOKS if stage == "pre-commit" else []
    lines = [
        "#!/bin/sh",
        "# Generated by farrier from the `hooks:` front matter of the installed skills and policies.",
        "# Do not edit — `farrier install` rewrites it. Add or remove a hook by changing",
        "# the skill or policy that declares it, or by changing what `agents.yml` selects.",
        "set -eu",
        "",
        'root=$(git rev-parse --show-toplevel)',
        "",
    ]
    if not hooks:
        lines += [f"# No installed skill declares a {stage} hook.", "", *user_hooks]
        return "\n".join(lines)
    lines += [
        'if [ -z "${STABLEMATE_CACHE_DIR:-}" ]; then',
        f"  STABLEMATE_CACHE_DIR={shlex.quote(str(cache_root()))}",
        "fi",
        "export STABLEMATE_CACHE_DIR",
        "",
    ]
    for hook in hooks:
        lines += [f"# {hook.skill}"]
        candidates = " ".join(
            f'"$root/{root}/{hook.skill}/{hook.run}"' for root in hook.roots
        )
        call = '  python3 "$gate" "$@"' if hook.run.endswith(".py") else '  "$gate" "$@"'
        lines += [
            f"for gate in {candidates}; do",
            '  [ -f "$gate" ] || continue',
            call,
            "  break",
            "done",
            "",
        ]
    lines += user_hooks
    return "\n".join(lines)


def run_user_hooks(repo: Path, gates: list[Path]) -> int:
    """Run each user-library gate from *repo*, stopping at the first that refuses the commit."""
    env = {
        **os.environ,
        "STABLEMATE_CACHE_DIR": os.environ.get("STABLEMATE_CACHE_DIR") or str(cache_root()),
    }
    for gate in gates:
        status = subprocess.run(("python3", str(gate)), cwd=repo, env=env, check=False).returncode
        if status:
            return status
    return 0




def _make_executable(path: Path) -> None:
    mode = path.stat().st_mode
    path.chmod(mode | ((mode & 0o444) >> 2))


def _set_hooks_path(repo: Path, value: str) -> None:
    subprocess.run(
        ("git", "config", "core.hooksPath", value),
        cwd=repo,
        capture_output=True,
        check=False,
    )


def install_manager(
    repo: Path, manager: str, *, dry_run: bool = False
) -> list[str]:
    """Splice (or strip) farrier's fence."""
    if manager == "none":
        removed = []
        for rel in (rel for rels in _FENCE_FILES.values() for rel in rels):
            path = repo / rel
            if not path.is_file():
                continue
            existing = path.read_text(encoding="utf-8")
            stripped = unsplice(existing)
            if stripped != existing:
                if not dry_run:
                    path.write_text(stripped, encoding="utf-8")
                removed.append(rel)
        prefix = "[dry-run] " if dry_run else ""
        return [
            f"{prefix}Removed farrier's hook entry from {rel}" for rel in removed
        ]

    messages: list[str] = []
    for rel in _FENCE_FILES[manager]:
        messages.extend(_install_fence(repo, manager, rel, dry_run=dry_run))
    if manager == "githooks":
        if dry_run:
            messages.append("[dry-run] would set core.hooksPath to .githooks")
        else:
            _set_hooks_path(repo, ".githooks")
    return messages


def _install_fence(repo: Path, manager: str, rel: str, *, dry_run: bool) -> list[str]:
    path = repo / rel
    existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    if LEGACY_HOOK_MARKER in existing:
        existing = ""
    if manager in ("husky", "githooks") and not existing.strip():
        existing = _shell_preamble(rel)

    desired = splice(existing, fence(body_for(manager, rel)))
    if manager == "pre-commit" and not any(
        line.startswith("repos:") for line in desired.splitlines()
    ):
        desired = "repos:\n" + desired

    messages: list[str] = []
    if desired != (path.read_text(encoding="utf-8") if path.is_file() else None):
        prefix = "[dry-run] " if dry_run else ""
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(desired, encoding="utf-8")
        messages.append(f"{prefix}Wired farrier's hooks into {rel}")
    if manager in ("husky", "githooks"):
        if dry_run:
            messages.append(f"[dry-run] would set executable bit on {rel}")
        else:
            _make_executable(path)
    return messages


def install_runner(
    repo: Path,
    hooks: list[SkillHook] | None,
    *,
    dry_run: bool = False,
) -> list[str]:
    """Regenerate each stage's ``.agents/hooks/<stage>`` runner from the declared hooks."""
    if hooks is None:
        if dry_run:
            return [
                f"[dry-run] would regenerate {', '.join(RUNNERS.values())} "
                "(no library — run 'farrier install' to refresh)"
            ]
        return []
    messages: list[str] = []
    for stage in STAGES:
        rel = RUNNERS[stage]
        path = repo / rel
        text = runner_text(hooks, stage)
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if dry_run:
            messages.append(f"[dry-run] would regenerate {rel}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        _make_executable(path)
        messages.append(f"Wrote {rel}")
    return messages


def fence_drift(repo: Path, manager: str) -> list[str]:
    """The fenced regions that no longer match what farrier would write."""
    if manager == "none":
        return [
            rel
            for rels in _FENCE_FILES.values()
            for rel in rels
            if (repo / rel).is_file()
            and fenced_body((repo / rel).read_text(encoding="utf-8")) is not None
        ]
    return [
        rel
        for rel in _FENCE_FILES[manager]
        if not (repo / rel).is_file()
        or fenced_body((repo / rel).read_text(encoding="utf-8")) != body_for(manager, rel)
    ]
