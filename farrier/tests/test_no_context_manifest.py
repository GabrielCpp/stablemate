"""An install writes no context manifest anywhere and sweeps the old in-repo copies."""

from __future__ import annotations

from pathlib import Path

import pytest

from farrier._vendor.stablemate_core.base_cache import CACHE_DIR_ENV
from farrier.install import main
from test_skills_from import make_library


def _install(repo: Path, library: Path, *extra: str) -> int:
    return main(["install", "--repo", str(repo), "--library", str(library), *extra])


def _repo(tmp_path: Path) -> tuple[Path, Path]:
    library = make_library(tmp_path)
    repo = tmp_path / "acme"
    repo.mkdir()
    (repo / "agents.yml").write_text(
        "agents:\n  claude: true\nskills:\n  - db\n", encoding="utf-8"
    )
    return repo, library


def test_install_writes_no_context_manifest_anywhere(tmp_path, monkeypatch: pytest.MonkeyPatch):
    cache = tmp_path / "cache"
    monkeypatch.setenv(CACHE_DIR_ENV, str(cache))
    repo, library = _repo(tmp_path)

    assert _install(repo, library) == 0

    assert not (cache / "farrier").exists()
    assert not list(repo.rglob("agents-context*.json"))


def test_install_removes_the_legacy_in_repo_manifests(tmp_path):
    repo, library = _repo(tmp_path)
    legacy = repo / ".agents"
    legacy.mkdir()
    (legacy / "agents-context.json").write_text("{}", encoding="utf-8")
    (legacy / "agents-context.claude.json").write_text("{}", encoding="utf-8")

    assert _install(repo, library, "--check") == 1
    assert _install(repo, library) == 0

    assert not list(legacy.glob("agents-context*.json"))
    assert _install(repo, library, "--check") == 0


def test_install_drops_the_old_policy_and_manifest_ignore_lines(tmp_path):
    repo, library = _repo(tmp_path)
    (repo / ".gitignore").write_text(
        ".agents/agents.mk\n.agents/agents-context.json\n.agents/workflows/\n",
        encoding="utf-8",
    )

    assert _install(repo, library) == 0

    lines = (repo / ".gitignore").read_text().splitlines()
    assert ".agents/agents.mk" not in lines
    assert ".agents/agents-context.json" not in lines
    assert ".agents/runs/" in lines


def test_install_sweeps_the_legacy_policies_folder(tmp_path):
    repo, library = _repo(tmp_path)
    assert _install(repo, library) == 0
    legacy = repo / ".agents" / "policies" / "old"
    legacy.mkdir(parents=True)
    (legacy / "POLICY.md").write_text(
        "<!--\nDO NOT EDIT — generated by farrier from the agent library.\n-->\nold\n",
        encoding="utf-8",
    )

    assert _install(repo, library) == 0

    assert not (repo / ".agents" / "policies").exists()
