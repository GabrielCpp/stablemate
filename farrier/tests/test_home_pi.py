"""Pi's home: skills, rules, MCP servers, settings and guards reached through a generated extension."""

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from _guard_bridge_support import add_guard
from home_install import add_search_server, add_settings, add_skill_pair, install, seed

GUARD = '[user_library.pi]\nhooks = ["stub"]\n'
EXTENSION = ".pi/agent/extensions/farrier-guards.ts"
NODE = shutil.which("node")
CALL_EXTENSION = """
const register = (await import(process.argv[2])).default
const handlers = {}
register({ on: (name, handler) => (handlers[name] = handler) })
const [toolName, input] = JSON.parse(process.argv[3])
const ctx = { cwd: "/project", sessionManager: { getSessionId: () => "s" } }
const result = await handlers.tool_call({ toolName, input }, ctx)
console.log(JSON.stringify({ result: result ?? null, input }))
"""


def run_extension(home: Path, tool: str, args: dict) -> dict:
    assert NODE is not None
    module = home.parent / "extension.mjs"
    module.write_text((home / EXTENSION).read_text(encoding="utf-8"), encoding="utf-8")
    done = subprocess.run(
        [
            NODE,
            "--input-type=module",
            "-e",
            CALL_EXTENSION,
            "extension",
            str(module),
            json.dumps([tool, args]),
        ],
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
    )
    return json.loads(done.stdout)


def test_a_skill_lands_in_the_shared_agents_folder_with_path_references(
    home: Path, library: Path
) -> None:
    add_skill_pair(library)
    config = '[user_library.pi]\nskills = ["general/ship", "general/review"]\n'
    assert install(home, library, config) == 0
    shipped = (home / ".agents/skills/ship/SKILL.md").read_text(encoding="utf-8")
    assert "Read `../review/SKILL.md`" in shipped
    assert not (home / ".pi/agent/skills").exists()
    assert install(home, library, config, "--check") == 0


def test_the_rules_land_in_the_pi_agent_agents_md(home: Path, library: Path) -> None:
    roots = library / "library" / "roots"
    roots.mkdir()
    (roots / "rules.md").write_text(
        '---\ndescription: "Rules."\n---\n\nSay hello.\n', encoding="utf-8"
    )
    assert install(home, library, '[user_library.pi]\nroots = ["rules"]\n') == 0
    assert "Say hello." in (home / ".pi/agent/AGENTS.md").read_text(encoding="utf-8")


def test_a_server_lands_in_mcp_json_and_the_operators_servers_stay(
    home: Path, library: Path
) -> None:
    add_search_server(library)
    mine = seed(home / ".pi/agent/mcp.json", '{"mcpServers": {"mine": {"command": "tool"}}}\n')
    config = '[user_library.pi]\nmcp = ["search"]\n'
    assert install(home, library, config) == 0
    servers = json.loads(mine.read_text(encoding="utf-8"))["mcpServers"]
    assert servers["mine"] == {"command": "tool"}
    assert servers["search"]["command"] == "ostler"
    assert install(home, library, config, "--check") == 0


def test_settings_merge_and_the_operators_keys_stay(home: Path, library: Path) -> None:
    add_settings(library, '{"quietStartup": true}\n')
    mine = seed(home / ".pi/agent/settings.json", '{"theme": "dim"}\n')
    config = '[user_library.pi]\nsettings = ["prefs"]\n'
    assert install(home, library, config) == 0
    assert json.loads(mine.read_text(encoding="utf-8")) == {
        "theme": "dim",
        "quietStartup": True,
    }
    assert install(home, library, config, "--check") == 0


def test_a_settings_entry_with_hooks_is_refused_and_points_at_guards(
    home: Path, library: Path
) -> None:
    add_settings(library, '{"hooks": {}}\n')
    with pytest.raises(SystemExit) as refused:
        install(home, library, '[user_library.pi]\nsettings = ["prefs"]\n')
    assert "library/hooks guards" in str(refused.value)
    assert not (home / ".pi/agent/settings.json").exists()


def test_a_prompt_selected_for_pi_is_unsupported(home: Path, library: Path) -> None:
    with pytest.raises(SystemExit) as refused:
        install(home, library, '[user_library.pi]\nprompts = ["review"]\n')
    assert "prompts are Claude-only at user scope" in str(refused.value)


def test_a_guard_lands_as_one_extension_with_the_tool_map_and_the_block(
    home: Path, library: Path
) -> None:
    add_guard(library, "stub", "exit 0\n")
    assert install(home, library, GUARD) == 0
    text = (home / EXTENSION).read_text(encoding="utf-8")
    assert text.startswith("// generated by farrier\n")
    assert 'bash: (input) => [["Bash", { command: input.command }]]' in text
    assert 'find: (input) => [["Glob"' in text
    assert "{ block: true, reason: result.deny }" in text
    assert str(home / ".agents/hooks/stub") in text
    assert install(home, library, GUARD, "--check") == 0


def test_a_done_guard_is_refused_because_pi_is_reached_before_a_tool_only(
    home: Path, library: Path
) -> None:
    add_guard(library, "stub", "exit 0\n")
    (library / "library/hooks/stub/hook.yml").write_text(
        "command: sh {dir}/check.sh\nwhen: done\n", encoding="utf-8"
    )
    with pytest.raises(SystemExit) as refused:
        install(home, library, GUARD)
    assert "not_on" in str(refused.value)


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_the_extension_blocks_a_refused_call_and_allows_the_rest(
    home: Path, library: Path
) -> None:
    add_guard(library, "stub", "cat >/dev/null; echo refused >&2; exit 2\n")
    assert install(home, library, GUARD) == 0
    assert run_extension(home, "bash", {"command": "ls"})["result"] == {
        "block": True,
        "reason": "refused",
    }
    assert run_extension(home, "read", {"path": "a"})["result"] is None


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_the_extension_asks_once_per_edit_in_claude_shape(
    home: Path, library: Path
) -> None:
    seen = home.parent / "seen.jsonl"
    add_guard(library, "stub", f"cat >> {seen}; echo >> {seen}\n")
    assert install(home, library, GUARD) == 0
    edits = [{"oldText": "a", "newText": "b"}, {"oldText": "c", "newText": "d"}]
    assert (
        run_extension(home, "edit", {"path": "f.py", "edits": edits})["result"] is None
    )
    calls = [
        json.loads(line)
        for line in seen.read_text(encoding="utf-8").split("\n")
        if line
    ]
    assert [call["tool_input"] for call in calls] == [
        {"file_path": "f.py", "old_string": "a", "new_string": "b"},
        {"file_path": "f.py", "old_string": "c", "new_string": "d"},
    ]
    assert {call["tool_name"] for call in calls} == {"Edit"}
    assert calls[0]["session_id"] == "s"
    assert calls[0]["cwd"] == "/project"


def test_a_dropped_guard_takes_the_extension_with_it(home: Path, library: Path) -> None:
    add_guard(library, "stub", "exit 0\n")
    assert install(home, library, GUARD) == 0
    add_search_server(library)
    assert install(home, library, '[user_library.pi]\nmcp = ["search"]\n') == 0
    assert not (home / EXTENSION).exists()
