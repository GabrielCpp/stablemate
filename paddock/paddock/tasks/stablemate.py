"""The process boundary a paddock task drives stablemate across."""

from __future__ import annotations

import os
import shutil
import subprocess
import tomllib
from collections.abc import Iterator, Mapping
from contextlib import contextmanager
from pathlib import Path

import tomli_w
import yaml

from paddock import CommandResult, Run, project
from paddock._vendor.stablemate_core import config as core_config


class TrialError(RuntimeError):
    """A fixture or trial precondition that fails before anything has been measured."""


def git(*args: str, cwd: Path) -> str:
    proc = subprocess.run(
        ["git", *args], cwd=str(cwd), capture_output=True, text=True, check=False
    )
    if proc.returncode != 0:
        raise TrialError(f"git {' '.join(args)} in {cwd}: {proc.stderr.strip()}")
    return proc.stdout


def _describe(checkout: Path) -> list[str]:
    """What the toolchain looks like right now: its `git status --porcelain` lines, and the commit it is sitting on."""
    stashed = project.stashed_git_dir(checkout)
    where = ["--git-dir", str(stashed), "--work-tree", str(checkout)] if stashed.is_dir() else []
    lines = [line for line in git(*where, "status", "--porcelain", cwd=checkout).splitlines() if line]
    head = git(*where, "rev-parse", "HEAD", cwd=checkout).strip()
    return [*lines, f"committed — HEAD is now {head}"]


def pin_held(pin: project.Project | None) -> bool:
    """Whether a round got the pin it was configured for — not merely asked for one."""
    return pin is not None and pin.pinned


@contextmanager
def no_leaks(checkout: Path, *, pinned: bool) -> Iterator[None]:
    """Fail the round if the toolchain checkout changed while it ran."""
    before = set(_describe(checkout))
    yield
    leaked = sorted(set(_describe(checkout)) - before)
    if not leaked:
        return
    if pinned:
        raise TrialError(
            f"the round wrote into {checkout} instead of its sandboxes:\n"
            + "\n".join(leaked)
            + "\nrevert that before believing any number here"
        )
    raise TrialError(
        f"{checkout} changed while the round ran, and this round was not pinned — so "
        f"whether the round wrote this or somebody else did is not knowable from here:\n"
        + "\n".join(leaked)
        + "\nre-run pinned before believing any number here"
    )


def stablemate_dir() -> Path:
    """The stablemate checkout the trials drive `workhorse-coder` out of."""
    resolved = core_config.resolve_stablemate_dir()
    if resolved is None or not (resolved / "pyproject.toml").is_file():
        raise TrialError(
            "no `stablemate_dir` in the machine's stablemate config — the trials need a "
            "checkout to run `workhorse-coder` out of (set it with `farrier config`)"
        )
    return resolved


def stablemate_checkout(run: Run) -> Path:
    """The checkout *this run* drives, which is not always the operator's."""
    project = run.project
    if project is not None and (project / "pyproject.toml").is_file():
        return project
    return stablemate_dir()


def uv_run(checkout: Path, package: str) -> list[str]:
    """The `uv run` prefix that runs *checkout*'s own code, not this machine's."""
    return ["uv", "run", "--project", str(checkout), "--package", package]


def effective(run: Run) -> Path:
    return run.scratch / "stablemate-config.toml"


def pin_config(run: Run) -> None:
    """Write the effective stablemate config the trials run under, into `scratch/`."""
    machine = core_config.load_config()
    local = {
        name: str(value)
        for name in ("library_dir", "base_dir", "stablemate_dir", "worktree_dir")
        if isinstance(value := core_config.get_config_value(name, machine), str) and value
    }
    local["stablemate_dir"] = str(stablemate_checkout(run))
    if "library_dir" not in local:
        raise TrialError(
            "no `library_dir` in the machine's stablemate config — a run given --config "
            "inherits nothing from the machine's, so the library root has to come from here"
        )
    header = (
        "# Generated by a paddock task. The model tables come from the tracked\n"
        "# config; the paths below are this machine's and are why this file is not tracked.\n"
    )
    merged = {**tomllib.loads(run.config.read_text(encoding="utf-8")), **local}
    effective(run).write_text(header + tomli_w.dumps(merged), encoding="utf-8")


def install_agents(run: Run) -> list[CommandResult]:
    """Render the agents layer into each staged repo that carries an `agents.yml`, so its machine-local paths point at this run."""
    farrier = uv_run(stablemate_checkout(run), "farrier")
    results = [
        run.cli(
            *farrier, "farrier", "install", "--repo", str(repo),
            cwd=repo, log_name=f"farrier-install-{name}", check=True,
        )
        for name, repo in run.repos.items()
        if (repo / "agents.yml").is_file()
    ]
    if not results:
        raise TrialError(f"no staged repo has an agents.yml to install: {', '.join(run.repos)}")
    return results


def trial_artifacts(repo: Path) -> Path:
    """The artifacts dir of the trial whose repo is *repo*: a fresh sibling of it, never the user's."""
    return repo.with_name(f"{repo.name}.artifacts")


def trial_env(repo: Path, base: Mapping[str, str] | None = None) -> dict[str, str]:
    """*base* (default: this process's environment) with the artifacts dir pointed at the trial's."""
    return {
        **(os.environ if base is None else base),
        core_config.ARTIFACTS_DIR_ENV: str(trial_artifacts(repo)),
    }


def spec_dir(repo: Path, story: str) -> Path:
    """The story's spec folder in the trial that owns *repo*, as ostler resolves it."""
    from ostler.api import Ostler  # noqa: PLC0415 - a heavy import only a trial needs

    previous = os.environ.get(core_config.ARTIFACTS_DIR_ENV)
    os.environ[core_config.ARTIFACTS_DIR_ENV] = str(trial_artifacts(repo))
    try:
        return Path(Ostler(repo).spec_path(story))
    finally:
        if previous is None:
            os.environ.pop(core_config.ARTIFACTS_DIR_ENV, None)
        else:
            os.environ[core_config.ARTIFACTS_DIR_ENV] = previous


def _front_matter(path: Path) -> dict[str, object]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    head = text[4:].split("\n---", 1)[0]
    data = yaml.safe_load(head)
    return data if isinstance(data, dict) else {}


def _stage(source: Path, target: Path) -> None:
    if target.is_dir():
        shutil.rmtree(target)
    elif target.exists():
        target.unlink()
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(source, target)


def upgrade_layout(repo: Path) -> None:
    """Rename an old seed's slug spec folders to story ids, then stage every spec and epic out of *repo* into the trial's artifacts dir, and drop the staged epics from the copy's index."""
    specs = repo / "docs" / "specs"
    epics = repo / "docs" / "epics"
    if specs.is_dir():
        ids: dict[str, str] = {}
        for story_md in sorted([*repo.glob("docs/epics/*/stories/*/story.md"), *repo.glob("epics/*/stories/*/story.md")]):
            story_id = _front_matter(story_md).get("id")
            if isinstance(story_id, str) and story_id:
                ids[story_md.parent.name] = story_id
        for folder in sorted(specs.iterdir()):
            target = ids.get(folder.name)
            if folder.is_dir() and target and not (specs / target).exists():
                folder.rename(specs / target)
        staged = trial_artifacts(repo) / "specs"
        staged.mkdir(parents=True, exist_ok=True)
        for entry in sorted(specs.iterdir()):
            _stage(entry, staged / entry.name)
        shutil.rmtree(specs)
    if epics.is_dir():
        for epic in sorted(epics.iterdir()):
            _stage(epic, trial_artifacts(repo) / "epics" / epic.name)
        shutil.rmtree(epics)
        if (repo / ".git").exists():
            _ = git("rm", "-r", "--cached", "--quiet", "--ignore-unmatch", "--", "docs/epics", cwd=repo)
