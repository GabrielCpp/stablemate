def create_app() -> Litestar:
    return Litestar(
        route_handlers=[
            index,
            api_state,
            repos,
            files,
            file_content,
            worker_detail,
            diff,
            outbox_get,
            run_overview,
            api_history,
            archive_overview,
            history_retry,
            run_activity,
            archive_activity,
            run_records,
            archive_records,
            run_turn,
            archive_turn,
            run_search,
            archive_search,
            run_entry,
            archive_entry,
            outbox_post,
            inbox_get,
            inbox_post,
            refresh,
            push_progress,
            attend_queue,
            attend_sessions,
            attend_session,
            attend_stop,
            attend_settings_get,
            attend_settings_post,
            dispatch_queues,
            dispatch_enqueue,
            dispatch_items,
            dispatch_delete,
            dispatch_stop,
            push_blocked,
            push_exited,
            otlp_traces,
            otlp_metrics,
            otlp_logs,
            api_live,
            dashboard_ws,
            feed_ws,
            dashboard_sidecar,
            reload,
            create_static_files_router(path="/assets", directories=[ASSETS_DIR]),
        ],
        on_startup=[
            _bind_history_lock,
            _spawn_scan,
            _spawn_rules,
            _bind_live,
            _spawn_heartbeat,
            _spawn_archive,
            _spawn_summaries,
            _recover_attend,
            _recover_dispatch,
        ],
        on_shutdown=[_stop_rules, _stop_heartbeat, _stop_archive, _stop_summaries, pools.shutdown_all],
    )
